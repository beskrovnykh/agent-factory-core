"""Журнал запусков: единица учёта — ЗАДАЧА, а не сессия.

Сессий на одну задачу бывает несколько: работа, доработка после ревью,
проверка выката. Пока строка учёта равна сессии, настоящая цена задачи нигде
не видна — DEV-62 стоила $10,35, а показывалась как $9,15 и $1,20 в разных
строках. Поэтому здесь всё сворачивается к задаче, а заходы остаются внутри
неё числом и признаком переделки.

**Считаем события, а не статусы.** Статус в трекере двигает человек, и метрика
из статусов меряет его дисциплину, а не работу фабрики: 12.09.2026 две задачи
висели «In Progress» с 10.09 без исполнителя и без единой сессии, и счёт по
статусам показал бы три задачи в работе при одной настоящей. Здесь источник —
то, что случается само: каталог сессии, её `stats.json` и итоговая запись
транскрипта (см. `sessions.walk`).

Чего тут нет и почему. Отклонения и отмены (`REJECTED`, `CANCELLED`) —
решения людей, и раннер их не размечает: в сводке они будут нулём по
построению, а не по факту, и сводка об этом говорит прямо, вместо того чтобы
показать честный на вид ноль. Появится тот, кто их пишет, — цифра оживёт
сама, потому что считается по общему словарю исходов.

Часть ПРОДУКТА: как сворачивать заходы в задачу и что показывать в сводке,
одинаково у любой инсталляции.
"""
from __future__ import annotations

