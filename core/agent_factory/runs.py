# Потолок кругов: столько рабочих заходов задача может получить сама, без
# человека. Следующий возврат от проверки уходит принимающему кодом, а не
# по прозе контракта («третий возврат — на человека»): прозу модель считает по
# комментариям и ошибается, а здесь счёт — по следам заходов на диске.
# 0 — потолка нет. Живой счёт на 14.09.2026: DEV-4 ×7, DEV-76/46/43/18 ×6.
MAX_WORK_ROUNDS = int(os.environ.get("AGENT_MAX_WORK_ROUNDS", "3") or 0)

# Полный словарь исходов запуска. Держится в паре с `runner.OUTCOMES`: там его
# пишут, здесь читают. Копия, а не импорт, — намеренно: раннер это отдельный
# процесс на хосте инсталляции, а пакет приёма уезжает зависимостью в чужой
# контейнер, где никакого `runner` нет. Расхождение ловит тест.
OUTCOMES = ("VERIFIED", "READY_FOR_HUMAN", "FAILED", "REJECTED",
            "CANCELLED", "PAUSED", "WAITING_CI", "WAITING_LIMIT")

# Исходы, которые раннер выставить не может: они про решения людей. Ноль
# напротив них — «некому было записать», а не «не случалось», и сводка
# обязана это различать. `WAITING_CI` здесь был до DEV-16: теперь его пишет
# раннер — сессия, отдавшая ожидание проверок подметальщику.
NOT_WRITTEN_BY_RUNNER = ("REJECTED", "PAUSED")
# `CANCELLED` пишут двое: ворота перед постановкой проверки (DEV-86,
# `deploy.write_skip_record` — отсечённая проверка, заход за $0, причина в
# `stats.json` («ворота»)) и раннер по команде `/stop` (DEV-91 — снятая
# человеком сессия, причина в `stats.json` («снята»)).

# Заходы, которые считаются РАБОЧИМИ: по их числу видно переделку. Проверка
# выката и приём постановки к переделке отношения не имеют — проверка бывает
# у любой сданной задачи, и записывать её в «делали дважды» значит объявить
# переделкой каждую нормально прошедшую задачу.
# Разрешения конфликта (`merge`, DEV-109) здесь намеренно НЕТ: задача уже
# сделана и проверена, ветка перестала вливаться от чужого мержа, и считать
# это переделкой значит отнимать у задачи круг за чужую работу.
WORK_KINDS = ("work", "работа", "incident", "дежурный", "")

# Заходы приёма постановки. Задачи в трекере у них ещё нет — это пачка
# пересланного, из которой она только собирается.
INTAKE_KINDS = ("intake", "приём")

# Ориентир из постановки: сколько принятых задач в день считается рабочим
# темпом. Не норма и не план — линия, относительно которой день читается.
PACE = (4, 8)

DAY = 86400


def _is_work(session: dict) -> bool:
    return str(session.get("род") or "") in WORK_KINDS


def _stage(session: dict) -> dict:
    """Один заход как этап задачи. Короткий словарь, а не вся сессия: этапы
    уезжают в карточку учёта, а она живёт в трекере и читается человеком."""
    return {
        "род": str(session.get("род") or ""),
        "когда": _stamp(session.get("touched") or session.get("started") or 0),
        "секунд": int(session.get("секунд") or 0),
        "usd": round(float(session.get("стоимость") or 0), 2),
        "исход": str(session.get("исход") or ""),
        # Точка проверки (`режим` из stats.json). Нужна именно здесь: без неё
        # `VERIFIED` подписывается «выкат проверен» на проверке ветки, где
        # выката не было (DEV-115). У работы и приёма поля нет — пусто.
        "режим": str(session.get("режим") or ""),
        "остановка": str(session.get("остановка") or ""),
        # Идущий и брошенный заход — не «исход не размечен». «Некому было
        # записать» и «ещё пишется» это разные факты, и на карточке задачи
        # они читаются по-разному: первое требует объяснения, второе — нет.
        "идёт": bool(session.get("идёт")),
        "брошена": bool(session.get("брошена")),
    }


def by_task(sessions: list[dict], verdicts: dict | None = None) -> list[dict]:
    """Сессии → строки задач. Сортировка — по последнему касанию, свежее выше.

    `verdicts` — оценки человека, ключ = имя каталога сессии (так их ставит
    страница). Задача берёт САМУЮ ПОЗДНЮЮ оценку своих заходов: оценивают
    работу, а работа — это задача целиком, и «переделывали» относится к ней,
    а не к одному из заходов.
    """
    verdicts = verdicts or {}
    groups: dict[str, list[dict]] = {}
    for s in sessions:
        groups.setdefault(str(s.get("task") or s.get("name") or "?"), []).append(s)

    rows = []
    for task, got in groups.items():
        # При равном времени старта порядок решает имя каталога, а не
        # файловая система: два захода одной секунды бывают (`sessions.walk`
        # берёт ctime), и от их порядка зависит, какой заход считается
        # последним, — то есть куда ляжет оценка задачи. То же правило, что у
        # `last_verify` и `evidence.last_checks`.
        got = sorted(got, key=lambda s: (s.get("started") or 0,
                                         str(s.get("name") or "")))
        work = [s for s in got if _is_work(s)]
        done = [s for s in got if not s.get("идёт")]
        # Исход задачи — исход последнего ЗАКОНЧЕННОГО захода. Не «лучший из»:
        # проверка выката идёт после работы, и если после неё завели ещё один
        # заход, задача снова в работе, чем бы проверка ни кончилась.
        last = next((s for s in reversed(done) if s.get("исход")), None)
        outcome = str((last or {}).get("исход") or "")
        # Точка проверки берётся у ТОГО ЖЕ захода, что дал исход: подпись
        # исхода говорит про него, и режим соседнего захода подписал бы
        # проверку ветки выкатом (DEV-115).
        outcome_mode = str((last or {}).get("режим") or "")
        marks = [(verdicts.get(s["name"]) or {}).get("оценка", "")
                 for s in got if s.get("name") in verdicts]
        # Куда класть оценку задачи. Оценка хранится по имени каталога
        # сессии, а ставят её теперь на карточке ЗАДАЧИ — значит нужен один
        # заход, который её держит. Берём тот, у кого она уже есть: иначе
        # повторное нажатие («снять оценку») положило бы пустоту новому
        # заходу, а старая осталась бы лежать и читалась бы дальше.
        marked = [s["name"] for s in got
                  if (verdicts.get(s["name"]) or {}).get("оценка")]
        started = min((s.get("started") or 0) for s in got)
        touched = max((s.get("touched") or 0) for s in got)
        rows.append({
            "задача": task,
            "заходов": len(got),
            "рабочих заходов": len(work),
            # Приёмная пачка — ещё НЕ задача: в трекере её нет, номер у неё
            # свой (`INTAKE-<хэш>`), и карточке учёта лечь некуда. Расход при
            # этом настоящий, и прятать его нельзя — поэтому не «выбросить»,
            # а «считать отдельно».
            "постановка": all(str(x.get("род") or "") in INTAKE_KINDS
                              for x in got),
            # Переделка — второй рабочий заход по тому же идентификатору.
            # Событие, а не мнение: доработка после ревью поднимает сессию
            # сама, её никто не размечает руками.
            "переделка": len(work) >= 2,
            "идёт": any(s.get("идёт") for s in got),
            "брошена": any(s.get("брошена") for s in got),
            "исход": outcome,
            "режим": outcome_mode,
            "оценка": next((m for m in reversed(marks) if m), ""),
            "оценить": marked[-1] if marked else str(got[-1].get("name") or ""),
            # Цена задачи ЦЕЛИКОМ — то самое единственное число, которое
            # сравнимо с ценой человеко-часа.
            "стоимость": round(sum(float(s.get("стоимость") or 0) for s in got), 2),
            # Активная работа — сумма заходов. Календарный срок — от первого
            # захода до последнего касания: он включает ожидание между ними и
            # почти всегда больше, а разница и есть то, что стоит смотреть.
            "секунд": sum(int(s.get("секунд") or 0) for s in got),
            "срок": int(max(0, touched - started)),
            "начато": started,
            "закончено": touched,
            "вход": sum(int(s.get("вход") or 0) for s in got),
            "выход": sum(int(s.get("выход") or 0) for s in got),
            "кэш": sum(int(s.get("кэш") or 0) for s in got),
            "пик_мб": max([int(s.get("память") or 0) for s in got] or [0]),
            # Этапы задачи — ЗАХОДЫ по порядку, каждый со своим родом, ценой и
            # исходом. Постановка → работа → доработка → проверка видна здесь
            # как последовательность событий, а не как история статусов: род
            # заходу ставит раннер, когда поднимает сессию.
            #
            # Чего в этом списке нет и почему: ревью идёт ВНУТРИ рабочего
            # захода (`/code-review` в той же сессии), отдельным событием его
            # не поймать; пайплайн и решение человека приходят не от раннера
            # — для них нужен источник, которого пока нет (событие мержа на
            # вебхуке `/deploy`, HLD п.2). Показывать их пустыми этапами
            # значит соврать, что мы их измеряем.
            "этапы": [_stage(x) for x in got],
            # Последствия задачи (DEV-56) — сумма по её заходам, по двум
            # причинам из четырёх. «Найдено» существовало до правки и вскрыто
            # ею, «внесено» — привнесено ею самой; смешивать их нельзя, это
            # противоположные оценки одной работы. «Часть решения» ни туда,
            # ни сюда: это объём выбранной тактики, а не последствие.
            "последствий найдено": sum(int(((x.get("шлюз") or {}).get("последствия")
                                            or {}).get("найдено") or 0) for x in got),
            "последствий внесено": sum(int(((x.get("шлюз") or {}).get("последствия")
                                            or {}).get("внесено") or 0) for x in got),
            # Тяжёлой задачу объявляет шлюз, а не тот, кто её ставил: по этому
            # числу видно, на скольких реальных случаях механизм отработал.
            "тяжёлая": any((x.get("шлюз") or {}).get("вердикт") == "тяжёлая"
                           for x in got),
        })
    return sorted(rows, key=lambda r: r["закончено"], reverse=True)


def work_rounds(work_root: str, ident: str) -> int:
    """Сколько РАБОЧИХ заходов уже было у задачи — по следам в рабочем
    каталоге, тем же счётом, что и «рабочих заходов» в карточке учёта.
    Проверки и приём не считаются (см. `WORK_KINDS`)."""
    if not work_root or not ident:
        return 0
    mine = [s for s in sess.walk(work_root) if str(s.get("task") or "") == ident]
    rows = by_task(mine)
    return int(rows[0]["рабочих заходов"]) if rows else 0


def last_verify(work_root: str, ident: str) -> dict:
    """Последняя СОСТОЯВШАЯСЯ проверка задачи по следам в рабочем каталоге:
    имя каталога, класс расхождения и точка (`класс`/`режим` из stats.json,
    DEV-89), первая строка её `verdict.txt`. Пусто — проверок не было.

    Отсев ворот (`deploy.write_skip_record`, исход `CANCELLED`) проверкой не
    считается: иначе первый же отсев «за unobservable» заслонил бы ту
    проверку, из-за которой он случился, и ворота на следующем заходе
    увидели бы «класса нет» — и поставили бы сессию, которую только что не
    ставили. Идущая сессия тоже не считается: её исход ещё не записан.

    `когда` — время её последней записи: по нему видно, что старше —
    проверка или снятие блокировки (`clearance`, DEV-105).
    """
    if not work_root or not ident:
        return {}
    mine = [s for s in sess.walk(work_root)
            if str(s.get("task") or "") == ident and str(s.get("род") or "") == "verify"
            and not s.get("идёт") and str(s.get("исход") or "") != "CANCELLED"]
    if not mine:
        return {}
    # Свежая — по времени старта, а при равенстве — по имени каталога: в нём
    # стоит штамп до секунды, и две проверки, заведённые в одну секунду,
    # иначе упорядочивались бы тем, в каком порядке их отдала файловая
    # система (на tmpfs в CI везло, на ext4 хоста — нет).
    s = max(mine, key=lambda x: (x.get("started") or 0.0, x.get("name") or ""))
    line = ""
    try:
        with open(os.path.join(work_root, s["name"], "verdict.txt")) as f:
            line = next((ln.strip() for ln in f if ln.strip()), "")[:300]
    except Exception:
        pass
    return {"name": s["name"], "класс": str(s.get("класс") or ""),
            "режим": str(s.get("режим") or ""), "вердикт": line,
            "когда": float(s.get("touched") or s.get("started") or 0.0)}


# ── снятие блокировки «наблюдать негде» (DEV-105) ───────────────────────────
#
# За `unobservable` следующая проверка в той же точке не ставится (DEV-89), и
# до 15.09.2026 снять это было НЕЧЕМ: точка меняется только мержем, а проверка
# после мержа у client-b выключена — задача запиралась навсегда. На DEV-66
# препятствием были мёртвые токены личностей; их починили в тот же вечер, и
# сказать об этом фабрике было нечем.
#
# Поэтому у блокировки есть условие снятия — явный сигнал человека
# (`commands.Unblock`): отдельная запись рядом с записями проверок, с тем,
# КТО и КОГДА его дал. Запись прошлой проверки при этом не трогается: она
# свидетельство состоявшегося, и править её значит подделывать вердикт.
#
# Почему рядом с проверками, а не в redis: блокировку держат следы в рабочем
# каталоге, и снятие обязано лежать там же — иначе «заперто» и «отперто»
# живут в двух хранилищах с разными сроками жизни, и расхождение между ними
# никто не заметит. Срока у записи нет намеренно: она отпускает только те
# проверки, что кончились ДО неё (см. `deploy.decide`), поэтому следующая
# `unobservable` запирает задачу снова, а лежалая запись безвредна.
CLEARANCES_DIR = "_clearances"

# Имя команды, которой сигнал даётся. Держится здесь, а не в `commands.py`:
# его называет причина отсева (`deploy.decide`), и человек обязан прочитать в
# ней ту же команду, которая на самом деле работает.
UNBLOCK_COMMAND = "unblock"

# Идентификатор задачи приезжает из сообщения человека и становится ИМЕНЕМ
# ФАЙЛА. Отсюда проверка формы, а не доверие вызывающему: `/unblock ../../x`
# не должен ничего записать за пределами каталога.
IDENT_FORM = re.compile(r"^[A-Za-z][A-Za-z0-9]*-\d+$")


def clearance_path(work_root: str, ident: str) -> str:
    """Файл записи о снятии блокировки. Пусто — идентификатор не той формы
    или каталога нет."""
    if not work_root or not IDENT_FORM.match(str(ident or "")):
        return ""
    return os.path.join(work_root, CLEARANCES_DIR, f"{ident.upper()}.json")


def clearance(work_root: str, ident: str) -> dict:
    """Последнее снятие блокировки по задаче: `кто`, `почему`, `когда`
    (unix-время). Пусто — сигнала не было."""
    path = clearance_path(work_root, ident)
    if not path:
        return {}
    try:
        with open(path) as f:
            got = json.load(f)
    except FileNotFoundError:
        return {}
    except Exception as e:
        log.warning("снятие блокировки %s не прочитано (%s) — считаю, что его "
                    "не было", ident, e)
        return {}
    if not isinstance(got, dict) or not got.get("когда"):
        return {}
    return {"задача": str(got.get("задача") or ident), "кто": str(got.get("кто") or ""),
            "почему": str(got.get("почему") or ""), "когда": float(got["когда"])}


def clear_block(work_root: str, ident: str, by: str, why: str,
                at: float | None = None) -> dict:
    """Записать сигнал «препятствие снято». Возвращает запись; исключение —
    если записать не вышло: команда обязана сказать человеку правду, а не
    ответить «снял» на несделанное.

    Сигнал один на задачу: второй переписывает первый. Накапливать их незачем
    — блокировку держит последняя проверка, и отпускает её последний сигнал.
    """
    path = clearance_path(work_root, ident)
    if not path:
        raise ValueError(f"не могу записать снятие блокировки: "
                         f"{'нет рабочего каталога' if not work_root else f'{ident} — не идентификатор задачи'}")
    rec = {"задача": ident.upper(), "кто": str(by or ""), "почему": str(why or ""),
           "когда": time.time() if at is None else float(at)}
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(rec, f, ensure_ascii=False)
    os.replace(tmp, path)
    log.info("снятие блокировки %s записано: кто %s, почему %s",
             rec["задача"], rec["кто"] or "?", rec["почему"] or "?")
    return rec


def rounds_exhausted(work_root: str, ident: str,
                     limit: int = MAX_WORK_ROUNDS) -> int:
    """Число заходов, если потолок выбран, иначе 0. Потолок 0 — выключен."""
    if limit <= 0:
        return 0
    n = work_rounds(work_root, ident)
    return n if n >= limit else 0


def needs_human(row: dict) -> bool:
    """Потребовала ли задача человека.

    Считаем по следам, а не по опросу: либо её переделывали (значит вернули с
    ревью), либо заход оборвался или брошен — тогда без человека она не
    сдвинется. Оценка тоже след человека, но она про ценность, а не про то,
    что ему пришлось вмешаться, и сюда не идёт.
    """
    return bool(row.get("переделка") or row.get("брошена")
                or row.get("исход") in ("FAILED", "REJECTED"))


def digest(rows: list[dict], since: float, until: float | None = None) -> dict:
    """Числа сводки за окно. Задача попадает в окно по ПОСЛЕДНЕМУ касанию.

    Не по началу: задача, начатая вчера и сданная сегодня, — сегодняшний
    результат, и в дневной сводке она нужна там, где её сдали. Иначе день
    сдачи выглядит пустым, а вчерашний — задним числом другим.
    """
    until = time.time() if until is None else until
    got = [r for r in rows if since <= r["закончено"] <= until]
    # Задачи и приёмные пачки считаются раздельно: пачка задачей не является,
    # и сложив их, мы объявили бы начатыми задачи, которых в трекере нет.
    # А деньги и токены суммируются по ВСЕМУ окну: приём стоит настоящих
    # денег, и сводка, где расход не сходится с реальностью, бесполезна.
    tasks = [r for r in got if not r["постановка"]]
    by_outcome = {o: len([r for r in tasks if r["исход"] == o])
                  for o in OUTCOMES}
    idle = [r for r in tasks if r["идёт"]]
    closed = [r for r in tasks if not r["идёт"]]
    return {
        "с": since,
        "по": until,
        # Ширину окна считает сводка, а не читатель по разнице «с» и «по».
        # Читатель получал бы её из двух РАЗНЫХ вызовов `time.time()` и на
        # ровно суточном окне промахивался на микросекунду — а от этого
        # зависит, разложить ли принятое по дням или назвать одним числом.
        "окно": round(until - since),
        "задач": len(tasks),
        "постановок": len(got) - len(tasks),
        # По числу СТРОК решается, пустое окно или нет: окно из одних приёмов
        # не пустое — в нём потрачены деньги.
        "строк": len(got),
        "идёт": len(idle),
        "по исходам": by_outcome,
        # Заход раннера прежней версии исхода не писал. Такие задачи обязаны
        # быть видны отдельной строкой: иначе первая же сводка после выката
        # покажет нули во всех исходах, и это прочитается как «фабрика ничего
        # не сделала», а не как «раннер ещё не перезапущен».
        "без отметки": len([r for r in tasks if not r["исход"]]),
        # Три вопроса из постановки, каждый — своё число.
        "выкат подтверждён": by_outcome["VERIFIED"],
        "дошло до человека": by_outcome["READY_FOR_HUMAN"],
        "ждёт": by_outcome["WAITING_LIMIT"] + by_outcome["WAITING_CI"],
        "зависло": len([r for r in tasks if r["брошена"]]),
        "переделок": len([r for r in tasks if r["переделка"]]),
        # Шлюз тяжёлой задачи (DEV-56). Три числа, потому что вопросов три:
        # часто ли он вообще срабатывает, сколько работа вскрыла и сколько
        # внесла сама.
        "тяжёлых": len([r for r in tasks if r.get("тяжёлая")]),
        "последствий найдено": sum(r.get("последствий найдено", 0) for r in tasks),
        "последствий внесено": sum(r.get("последствий внесено", 0) for r in tasks),
        "с человеком": len([r for r in tasks if needs_human(r)]),
        "стоимость": round(sum(r["стоимость"] for r in got), 2),
        "вход": sum(r["вход"] for r in got),
        "выход": sum(r["выход"] for r in got),
        "кэш": sum(r["кэш"] for r in got),
        "пик_мб": max([r["пик_мб"] for r in got] or [0]),
        # Средние — по ЗАКОНЧЕННЫМ задачам: у идущей срок ещё растёт, и
        # подмешивать её значит занижать обе цифры тем сильнее, чем больше
        # задач прямо сейчас в работе.
        "среднее активное": round(sum(r["секунд"] for r in closed) / len(closed))
                            if closed else 0,
        "средний срок": round(sum(r["срок"] for r in closed) / len(closed))
                        if closed else 0,
        "по дням": accepted_by_day(tasks, since, until),
    }


def accepted_by_day(rows: list[dict], since: float, until: float) -> list[dict]:
    """Принятые задачи по суткам окна — против ориентира 4–8 в день.

    «Принято» здесь — подтверждённый выкат (`VERIFIED`): единственный исход,
    которого никто не набирал руками. Дошедшее до человека сюда не идёт:
    открытый запрос на слияние задачей не является.
    """
    out = []
    day = int(since // DAY) * DAY
    while day <= until:
        got = [r for r in rows if day <= r["закончено"] < day + DAY]
        out.append({
            "день": day,
            "принято": len([r for r in got if r["исход"] == "VERIFIED"]),
            "задач": len(got),
        })
        day += DAY
    return out


def human_dur(seconds: float) -> str:
    seconds = int(max(0, seconds))
    if seconds < 60:
        return f"{seconds} с"
    if seconds < 3600:
        return f"{seconds // 60} мин"
    hours, minutes = seconds // 3600, (seconds % 3600) // 60
    return f"{hours} ч {minutes} мин" if minutes else f"{hours} ч"


def _pace_word(n: int) -> str:
    low, high = PACE
    if n < low:
        return "ниже ориентира"
    if n > high:
        return "выше ориентира"
    return "в ориентире"


def digest_text(d: dict, title: str = "За сутки",
                tokens: object = None) -> str:
    """Сводка словами. Уходит в чат, поэтому короткая и без таблиц.

    Пустое окно — отдельная ветка, а не нули: «начато 0, принято 0, $0» на
    телефоне читается как поломка счётчика, и разбираться человек идёт не
    туда. Прямая фраза дешевле.
    """
    fmt = tokens if callable(tokens) else str
    if not d.get("строк"):
        return (f"📊 {title}: запусков не было.\n"
                f"Это про журнал фабрики, а не про трекер: задача без единой "
                f"сессии сюда не попадает.")

    lines = [f"📊 {title}: {d['задач']} задач(и)."]
    if d.get("постановок"):
        lines.append(f"Плюс {d['постановок']} приём(а/ов) постановки — задачи "
                     f"в трекере у них ещё нет, но расход ниже их учитывает.")
    if d["идёт"]:
        lines.append(f"В работе прямо сейчас: {d['идёт']}.")
    lines.append(
        f"Выкат подтверждён: {d['выкат подтверждён']}. "
        f"Дошло до человека и ждёт решения: {d['дошло до человека']}. "
        f"Не дошло: {d['по исходам']['FAILED']}.")
    waiting = []
    if d["ждёт"]:
        waiting.append(f"ждёт внешнего: {d['ждёт']}")
    if d["зависло"]:
        waiting.append(f"зависло: {d['зависло']}")
    if waiting:
        lines.append("; ".join(waiting).capitalize() + ".")
    lines.append(
        f"Переделок: {d['переделок']}. "
        f"Потребовали человека: {d['с человеком']} из {d['задач']}.")
    # Строка шлюза печатается, только если он срабатывал или что-то потянул:
    # три нуля в каждой сводке приучают их не читать, а по ним и надо будет
    # судить, работает ли механизм.
    if d.get("тяжёлых") or d.get("последствий найдено") or d.get("последствий внесено"):
        lines.append(
            f"Тяжёлых задач (шлюз): {d.get('тяжёлых', 0)}. "
            f"Последствий найдено: {d.get('последствий найдено', 0)}, "
            f"внесено самой правкой: {d.get('последствий внесено', 0)}.")
    lines.append(
        f"Время: активной работы в среднем {human_dur(d['среднее активное'])}, "
        f"полный срок {human_dur(d['средний срок'])}.")
    lines.append(
        f"Расход: ${d['стоимость']:.2f}, "
        f"{fmt(d['вход'] + d['выход'] + d['кэш'])} токенов "
        f"(из них кэш {fmt(d['кэш'])}), пик памяти {d['пик_мб']} МБ.")

    # По суткам разбиваем только окно ШИРЕ суток. Само окно скользящее, и
    # ровно сутки почти всегда задевают две календарные даты — разложив их по
    # датам, мы показали бы «2 и 3» там, где принято пять, и человек читал бы
    # оба числа как недобор.
    if d["окно"] > DAY:
        lines.append("Принято по дням: " + ", ".join(
            str(x["принято"]) for x in d.get("по дням") or [])
            + f" (ориентир {PACE[0]}–{PACE[1]} в день).")
    else:
        n = d["выкат подтверждён"]
        lines.append(f"Принято за сутки: {n} — {_pace_word(n)} "
                     f"{PACE[0]}–{PACE[1]}.")

    if d.get("без отметки"):
        lines.append(
            f"Без отметки исхода: {d['без отметки']} — это заходы раннера "
            f"прежней версии, он исхода не писал. Пока они не вытеснятся "
            f"новыми, строка про исходы выше считает не по всем задачам.")

    missing = [o for o in NOT_WRITTEN_BY_RUNNER if not d["по исходам"][o]]
    if missing:
        lines.append(
            "Нулями идут исходы, которые пока некому записать: "
            + ", ".join(missing)
            + ". Это про отсутствие писателя, а не про отсутствие случаев.")
    return "\n".join(lines)


# ── карточка учёта на задачу ────────────────────────────────────────────────

# Заголовок карточки. Он же — метка, по которой писатель находит СВОЙ
# комментарий, чтобы поправить его, а не завести второй.
#
# Меткой НЕ может быть ключ машиночитаемого блока (`"учёт": 1`), как было
# сначала: ровно эту подстроку человек пишет сам, когда обсуждает формат
# карточки в той же задаче. В DEV-18 так и вышло — согласованный HLD приводит
# блок примером, и писатель принял бы HLD за свою карточку и заменил его
# телом учёта. Поэтому метка это ПЕРВАЯ СТРОКА комментария целиком, и в ней
# стоит номер задачи: процитировать блок внутри обсуждения можно, а начать
# свой комментарий ровно нашим заголовком — это уже вставить карточку, а не
# сослаться на неё.
CARD_HEAD = "### 🧾 Учёт: "


def card_marker(task: str) -> str:
    """Первая строка карточки этой задачи. По ней трекер узнаёт свою.

    Номер задачи внутри — не украшение: без него метка одинакова у всех
    карточек, и промах в выборе задачи превращается в правку чужой карточки.
    """
    return f"{CARD_HEAD}{task}"


def card_facts(row: dict) -> dict:
    """Машиночитаемая часть карточки. Ключи русские — как в остальном учёте:
    карточку читает и человек, и она не должна требовать словаря."""
    return {
        "учёт": 1,
        "задача": row["задача"],
        "заходов": row["заходов"],
        "переделка": row["переделка"],
        "минут": round(row["секунд"] / 60),
        "срок_минут": round(row["срок"] / 60),
        "usd": row["стоимость"],
        "токены": {"вход": row["вход"], "выход": row["выход"],
                   "кэш": row["кэш"]},
        "память_мб": row["пик_мб"],
        "исход": row["исход"],
        "оценка": row["оценка"],
        "начато": _stamp(row["начато"]),
        "закончено": _stamp(row["закончено"]),
        "этапы": row.get("этапы") or [],
    }


def _stamp(ts: float) -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(ts)) if ts else ""


OUTCOME_WORDS = {
    # «Проверка прошла», а не «выкат проверен»: точка проверки в самом исходе
    # не записана, и словарь по нему одному называть её не вправе (DEV-115).
    # Кто точку знает — зовёт `outcome_word`, и получает «ветка проверена»
    # или «выкат проверен».
    "VERIFIED": "проверка прошла",
    "READY_FOR_HUMAN": "сдано, ждёт человека",
    "FAILED": "не дошла до конца",
    "REJECTED": "возвращена",
    "CANCELLED": "отменена",
    "PAUSED": "приостановлена",
    "WAITING_CI": "ждёт пайплайн",
    "WAITING_LIMIT": "ждёт сброса лимита Claude",
}


# Подпись пройденной проверки по точке. Слово «выкат» — утверждение, что
# работа доехала до прода; на проверке ветки его не было, а карточка учёта и
# страница сессий писали его константой (DEV-115). Режим — тот же, что у
# раннера (`runner.MODES_AFTER_MERGE`) и у ворот (`deploy.point_of`).
VERIFIED_WORDS = {"branch": "ветка проверена", "state": "выкат проверен",
                  "build": "выкат проверен", "deploy": "выкат проверен"}


def outcome_word(outcome: str, mode: str = "") -> str:
    """Исход захода словами, с оглядкой на точку проверки.

    Режим не задан или незнаком — остаётся нейтральное слово из
    `OUTCOME_WORDS`: «проверку поставили руками» и «проверили выкат» это
    разные факты, и второй из первого не следует.
    """
    if outcome == "VERIFIED" and mode in VERIFIED_WORDS:
        return VERIFIED_WORDS[mode]
    return OUTCOME_WORDS.get(outcome, "исход не размечен")


# Как называется этап в карточке. Род заходу ставит раннер; словарь держит
# оба написания, потому что старые `stats.json` писали его по-английски.
STAGE_WORDS = {"work": "работа", "работа": "работа", "": "работа",
               "verify": "проверка", "проверка": "проверка",
               "intake": "приём", "приём": "приём",
               "incident": "дежурный", "дежурный": "дежурный",
               # Разрешение конфликта (DEV-109) — свой этап, не «работа»:
               # иначе в карточке учёта он читался бы как переделка, хотя
               # причина у него чужая, а круг по потолку он не тратит.
               "merge": "конфликт"}


# Значок этапа. Карточка задачи (DEV-100) показывает заходы столбиком, и по
# значку род захода виден раньше, чем прочитано слово. Значок — ВТОРОЙ способ
# сказать то же самое, а не единственный: слово рядом остаётся, иначе карточка
# требует словаря, которого у смотрящего с телефона нет.
STAGE_ICONS = {"работа": "🛠", "доработка": "♻️", "проверка": "🔬",
               "приём": "📥", "дежурный": "🚑", "конфликт": "🔀"}
# Значок захода, рода которого мы не знаем. Не «работа»: неизвестный род и
# работа — разные факты, и один значок на двоих врёт про второй.
UNKNOWN_ICON = "•"


def stages(row: dict) -> list[dict]:
    """Заходы задачи для показа: значок, чем был, чем кончился, чего стоил.

    Порядок — ХРОНОЛОГИЧЕСКИЙ, как в `этапы`: только в нём видно, какой
    рабочий заход второй, то есть где доработка. Переворачивать список под
    «свежее сверху» — дело того, кто рисует, а не того, кто считает.
    """
    out, work_seen = [], 0
    for st in row.get("этапы") or []:
        word = STAGE_WORDS.get(st.get("род") or "", st.get("род") or "заход")
        if word == "работа":
            work_seen += 1
            if work_seen > 1:
                word = "доработка"
        out.append({
            "этап": word,
            "значок": STAGE_ICONS.get(word, UNKNOWN_ICON),
            "когда": str(st.get("когда") or ""),
            "секунд": int(st.get("секунд") or 0),
            "usd": float(st.get("usd") or 0.0),
            "исход": str(st.get("исход") or ""),
            # Чем кончился — словами. Пустой исход это «некому было
            # записать», и молчать о нём нельзя: пустое место читается как
            # «всё хорошо».
            "чем кончился": ("идёт сейчас" if st.get("идёт") else
                             "брошена" if st.get("брошена") else
                             outcome_word(str(st.get("исход") or ""),
                                          str(st.get("режим") or ""))),
            "остановка": str(st.get("остановка") or ""),
        })
    return out


def stages_line(row: dict) -> str:
    """Этапы задачи одной строкой: «работа → проверка → доработка».

    Второй и следующие рабочие заходы называются доработкой — это и есть та
    самая переделка, видная как событие, а не как мнение. Нештатная остановка
    приписывается к этапу: без неё «работа → работа» читается как «делали
    дважды», хотя на деле первый заход упёрся в лимит ходов.
    """
    parts = []
    for st in stages(row):
        word = st["этап"]
        if st["остановка"]:
            word = f"{word} ({st['остановка']})"
        parts.append(word)
    return " → ".join(parts)


def extras(row: dict) -> list[str]:
    """Дополнительные пункты задачи — всё, что известно про неё сверх заходов
    и денег: переделка, суд шлюза, последствия, разрыв между работой и сроком.

    Одной задаче — одна карточка (DEV-100), поэтому пункты живут ЗДЕСЬ, а не
    отдельными плитками рядом: вторая плитка на ту же задачу — это ровно тот
    длинный список, из-за которого задачу приходилось собирать глазами.
    Пустой пункт не показывается: «последствий найдено 0» и «последствий
    никто не считал» с виду одинаковы, а это разные факты.
    """
    out = []
    if row.get("переделка"):
        out.append(f"переделка: рабочих заходов {row.get('рабочих заходов', 0)}")
    if row.get("тяжёлая"):
        out.append("шлюз: тяжёлая")
    if row.get("последствий найдено"):
        out.append(f"последствий найдено {row['последствий найдено']}")
    if row.get("последствий внесено"):
        out.append(f"последствий внесено {row['последствий внесено']}")
    # Календарный срок против активной работы: разница — это ожидание между
    # заходами, и оно почти всегда больше самой работы. Показываем, только
    # когда разница есть, — иначе строка повторяет соседнее число.
    if int(row.get("срок") or 0) > int(row.get("секунд") or 0):
        out.append(f"срок {human_dur(row['срок'])} при работе "
                   f"{human_dur(row.get('секунд') or 0)}")
    if row.get("постановка"):
        out.append("приёмная пачка — задачи в трекере ещё нет")
    return out


def card_body(row: dict) -> str:
    """Карточка учёта: текст для человека и блок для машины, в одном
    комментарии.

    Почему комментарий, а не поля задачи: набор полей у трекера настраивается
    вручную в каждой команде, у второй инсталляции он будет другим.
    Комментарий работает везде одинаково и переживает переезд трекера — и
    чистку диска, на котором лежат рабочие каталоги.
    """
    facts = card_facts(row)
    what = outcome_word(row["исход"], str(row.get("режим") or ""))
    line = stages_line(row)
    stages = f"Этапы: {line}.\n\n" if line else ""
    tries = (f"{row['заходов']} заход(а/ов), из них рабочих "
             f"{row['рабочих заходов']}")
    again = " — задачу переделывали" if row["переделка"] else ""
    body = (
        f"{card_marker(row['задача'])}\n\n"
        f"**${row['стоимость']:.2f}** за задачу целиком · {tries}{again}\n\n"
        f"Активной работы {human_dur(row['секунд'])}, "
        f"полный срок {human_dur(row['срок'])}. "
        f"Пик памяти {row['пик_мб']} МБ. Исход: {what}.\n\n"
        f"{stages}"
        f"Стоимость — сумма ВСЕХ заходов по задаче, включая доработку после "
        f"ревью и проверку выката: это то число, которое сравнимо с ценой "
        f"человеко-часа. Комментарий ведёт фабрика и обновляет его на месте — "
        f"отвечать на него не нужно.\n\n"
        f"```json\n{json.dumps(facts, ensure_ascii=False)}\n```"
    )
    return body


class Ledger:
    """Писатель карточек учёта: один комментарий на задачу, обновляемый.

    Рабочие каталоги живут до первой чистки диска или пересборки сервера и
    видны только владельцу токена — они источник, но не архив. Архив —
    трекер: он и так хранилище, второй базы заводить не надо, а разойтись с
    первой она успеет в первую же неделю.

    Обновляет, а не плодит: иначе задача с тремя заходами обрастает тремя
    карточками, и человек читает историю пересчётов вместо итога.
    """

    def __init__(self, tracker, log_):
        self.tracker = tracker
        self.log = log_

    def write(self, rows: list[dict]) -> int:
        """Разложить карточки по задачам. Возвращает, сколько записано.

        Ошибка по одной задаче не роняет остальные: трекер отвечает по сети,
        и одна недоступная задача (архивная, удалённая) не повод потерять
        учёт по всем.
        """
        if not callable(getattr(self.tracker, "upsert_comment", None)):
            # Трекер инсталляции до этого метода протокола ещё не дорос. Одна
            # строка вместо строки на каждую задачу: иначе журнал заваливает
            # сам себя, и настоящие отказы в нём не разглядеть.
            self.log.warning("трекер не умеет править комментарий — карточки "
                             "учёта не пишутся")
            return 0
        written = 0
        for row in rows:
            # Идущую пропускаем: числа ещё не окончательные, а карточка со
            # стоимостью на середине захода — цифра, которую потом придётся
            # объяснять. Приёмную пачку — потому что задачи в трекере нет, и
            # запрос по её номеру гарантированно вернёт «не найдено».
            if row["идёт"] or row["постановка"]:
                continue
            try:
                self.tracker.upsert_comment(row["задача"],
                                            card_marker(row["задача"]),
                                            card_body(row))
            except Exception as e:
                self.log.warning("карточка учёта %s не записана: %s",
                                 row["задача"], e)
                continue
            written += 1
        return written


class Journal:
    """Журнал как одна ручка: собрать, свернуть, показать, сохранить.

    Рабочий каталог читается ЦЕЛИКОМ, а окно накладывается потом. Иначе
    дневная сводка пересчитала бы карточку задачи по одним сегодняшним
    заходам и уронила бы её итог: вчерашние $9,15 исчезли бы, а осталось
    $1,20 — ровно та потеря цены задачи, ради которой единицей учёта и стала
    задача, а не сессия.
    """

    # Окна, которые умеет называть человек. День — умолчание: сводка нужна
    # чаще, чем раз в неделю, и набирать лишнее слово каждый раз незачем.
    WINDOWS = {
        "": (DAY, "За сутки"),
        "день": (DAY, "За сутки"),
        "сутки": (DAY, "За сутки"),
        "day": (DAY, "За сутки"),
        "неделя": (7 * DAY, "За неделю"),
        "неделю": (7 * DAY, "За неделю"),
        "week": (7 * DAY, "За неделю"),
    }
    HELP = ("Не понял период. Можно: `/digest` (за сутки) или "
            "`/digest неделя`.")

    def __init__(self, work_root: str, tracker=None, verdicts=None,
                 transport=None, notify_chat: str = ""):
        self.work_root = work_root
        # Трекера может не быть вовсе — тогда сводка считается и показывается,
        # а карточки не пишутся. Это хуже, чем с трекером, но лучше, чем
        # отсутствие сводки: считать и показывать можно без него.
        self.tracker = tracker
        self.verdicts = verdicts
        self.transport = transport
        self.notify_chat = notify_chat

    async def rows(self) -> list[dict]:
        import asyncio
        got = await asyncio.to_thread(sess.walk, self.work_root)
        marks = {}
        if self.verdicts is not None:
            marks = await self.verdicts.all()
        return by_task(got, marks)

    async def command(self, chat_id, args: str) -> str:
        """`/digest` и `/digest неделя`.

        Непонятый период — не молчание и не «покажу за сутки»: человек
        спрашивал не то, что получит, и узнает об этом только сверив числа.
        """
        word = (args or "").strip().lower()
        window = self.WINDOWS.get(word)
        if window is None:
            await self._say(chat_id, self.HELP)
            return "unknown-window"
        span, title = window
        if not self.work_root:
            await self._say(chat_id, "📊 Журнал запусков не настроен: у этой "
                                     "инсталляции нет рабочего каталога "
                                     "(AGENT_WORK_ROOT).")
            return "no-work-root"

        rows = await self.rows()
        # Одна отметка времени на оба конца окна: два вызова `time.time()`
        # дали бы окно шире суток на микросекунду, и дневная сводка поехала
        # бы по ветке недельной.
        now = time.time()
        since = now - span
        text = digest_text(digest(rows, since, now), title, sess.human_tokens)

        saved = await self._save([r for r in rows if r["закончено"] >= since])
        if saved:
            text += f"\n\nКарточек учёта в трекере обновлено: {saved}."

        # Сводка — общий факт фабрики, и место ей там же, где остальные её
        # уведомления. Но спросивший обязан получить ответ туда, где спросил:
        # молчание в личке он прочитает как поломку бота, а не как «ушло в
        # общий чат».
        to = self.notify_chat or chat_id
        await self._say(to, text)
        if str(to) != str(chat_id):
            await self._say(chat_id, "📊 Сводка отправлена в общий чат.")
        return "ok"

    async def _save(self, rows: list[dict]) -> int:
        if self.tracker is None or not rows:
            return 0
        import asyncio
        try:
            return await asyncio.to_thread(Ledger(self.tracker, log).write, rows)
        except Exception as e:
            # Учёт в трекере не должен утаскивать за собой сводку: числа уже
            # посчитаны, и показать их человеку можно и без архива.
            log.warning("карточки учёта не записаны: %s", e)
            return 0

    async def _say(self, chat_id, text: str) -> None:
        if self.transport is None:
            return
        try:
            await self.transport.send(chat_id, text)
        except Exception as e:
            # Молча проглоченная отправка неотличима от «команды нет»: в
            # журнале обязан остаться след, иначе разбираться человек пойдёт
            # в раннер, а не в транспорт.
            log.warning("сводка не отправлена в %s: %s", chat_id, e)
