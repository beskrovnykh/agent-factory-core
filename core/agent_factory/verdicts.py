"""Что работа стоила — и чего она стоила по делу.

Токены и минуты видно из коробки: их считает счётчик. Не видно главного —
пошла работа в дело или нет. Без этого статистика отвечает «сколько потратили»
и молчит про «зачем», а именно второе решает, прибавлять ли агенту слотов и
что показывать человеку, который спросит «и как, работает?».

Оценку ставит ЧЕЛОВЕК, и это не придирка к формату: три из четырёх исходов
машина не знает в принципе.

  • `ок` — приняли, переделывать не пришлось;
  • `ошибки` — сделано, но с браком: возвращали, правили, чинили за ним;
  • `постановка` — сделано по написанному, а написано было криво. Промах не
    агента, а того, кто ставил;
  • `мимо` — задача изначально была не нужна. Работа исправна, ценность ноль.

Последние два — про нас, а не про агента, и смешивать их с браком нельзя:
иначе «качество агента» начнёт падать от того, что мы плохо формулируем, и
цифра перестанет о чём-либо говорить.

Часть ПРОДУКТА: шкала одинакова у любой инсталляции, различается только то,
где хранить.
"""
from __future__ import annotations

import json
import logging
import time

log = logging.getLogger("intake")

KEY = "agent:verdicts"

# Порядок важен: он же порядок кнопок под сессией.
MARKS = (
    ("ок", "👍", "Принято", "Пошло в дело, переделывать не пришлось."),
    ("ошибки", "👎", "С ошибками", "Сделано, но возвращали и правили."),
    ("постановка", "📝", "Криво поставлена",
     "Сделано по написанному, а написано было плохо. Промах наш."),
    ("мимо", "🗑", "Не нужна была", "Работа исправна, ценность нулевая."),
)
NAMES = {key for key, *_ in MARKS}
# Чей это промах: агента или наш. Нужно, чтобы «качество агента» не падало от
# того, что мы криво формулируем.
OURS = ("постановка", "мимо")


def counted(verdicts: dict) -> dict:
    """Сводка по оценкам: сколько чего и какая доля удачных.

    Доля считается от ОЦЕНЁННЫХ, а не от всех сессий: неоценённая работа — это
    «ещё не смотрели», и записывать её в провал так же нечестно, как в успех.
    """
    got = [v.get("оценка") for v in verdicts.values() if v.get("оценка") in NAMES]
    by = {key: got.count(key) for key, *_ in MARKS}
    judged = len(got)
    agent = judged - by["постановка"] - by["мимо"]
    return {
        **by,
        "оценено": judged,
        # Доля удачных среди того, за что отвечает агент.
        "толк": round(100 * by["ок"] / agent) if agent else 0,
        # Доля работы, потраченной на то, что не следовало делать.
        "впустую": round(100 * (by["постановка"] + by["мимо"]) / judged)
                   if judged else 0,
    }


class Verdicts:
    """Оценки сессий. Живут в том же хранилище, что очередь и счётчики."""

    def __init__(self, store, key: str = KEY):
        self.store = store
        self.key = key

    async def all(self) -> dict:
        try:
            raw = await self.store.get(self.key)
        except Exception as e:
            log.warning("оценки не прочитаны: %s", e)
            return {}
        try:
            got = json.loads(raw) if raw else {}
        except Exception:
            log.error("оценки не разбираются — показываю пустыми")
            return {}
        return got if isinstance(got, dict) else {}

    async def put(self, session: str, mark: str, who: str = "") -> bool:
        """Поставить оценку. Пустая — снять."""
        if not session:
            return False
        if mark and mark not in NAMES:
            log.warning("оценка %r не из шкалы — не беру", mark)
            return False
        got = await self.all()
        if mark:
            got[session] = {"оценка": mark, "когда": time.time(), "кто": who}
        else:
            got.pop(session, None)
        try:
            await self.store.put(self.key, json.dumps(got, ensure_ascii=False), 0)
        except Exception as e:
            log.error("оценка сессии %s не сохранена: %s", session, e)
            return False
        log.info("оценка %s: %s", session, mark or "снята")
        return True
