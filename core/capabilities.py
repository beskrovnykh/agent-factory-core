def read_env(path: Path | None) -> dict:
    """Файл окружения инсталляции. Разбор тот же, что у `install.sh` и у
    `knowledge.read_env`: `KEY=значение`, кавычки по краям снимаются."""
    if path is None or not path.exists():
        return {}
    env = {}
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        val = val.strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
            val = val[1:-1]
        env[key.strip()] = val
    return env


def reason(cap: dict, env: dict) -> str:
    """Почему способность выключена. Пустая строка — включена.

    Причина возвращается готовой к печати, потому что читать её будет
    человек: «не задан AGENT_HOSTING_SOURCE», а не код состояния.
    """
    var = cap["переменная"]
    raw = (env.get(var) or "").strip()
    kind = cap["вид"]

    if kind == SWITCH:
        # Единственный вид, где ПУСТО значит «включено».
        return f"{var}={raw}" if raw.casefold() in SWITCH_OFF else ""

    if kind == INTERVAL:
        try:
            every = int(raw or "0")
        except ValueError:
            # Мусор вместо числа роняет приём на импорте, и это не «выключено»,
            # а поломка: говорим именно так, иначе строка успокоит.
            return f"{var}={raw} — не число, приём с этим не поднимется"
        # Порог тот же, что у `updater.Updater.watch`: `every <= 0 → return`.
        # Ноль и минус там одинаково значат «не слежу», и назвать минус
        # включённым значило бы соврать ровно в ту сторону, ради которой
        # список написан.
        return f"не задан {var}" if not raw else (f"{var}={raw}" if every <= 0 else "")

    if not raw:
        return f"не задан {var}"

    if kind == SOURCE and ":" not in raw:
        # Ровно тот же разбор, что у `updater.source_from_env`: без «:» она
        # пишет в журнал ошибку и возвращает None. Со стороны человека это
        # неотличимо от незаданной, поэтому и здесь — выключено.
        return f"{var}={raw} — нужно «модуль:Класс»"

    if kind == DIR:
        d = Path(raw)
        if not d.is_dir():
            return f"{var}={raw} — каталога нет"
        if not any(d.glob("*.md")):
            # Каталог есть, а записей нет: слой соберётся пустым, и со стороны
            # сессии это неотличимо от незаданного слоя.
            return f"{var}={raw} — в каталоге нет ни одной записи (*.md)"

    if kind == FILE:
        p = Path(raw)
        if not p.is_file():
            return f"{var}={raw} — файла нет"
        try:
            empty = not p.read_text(encoding="utf-8", errors="replace").strip()
        except OSError as e:
            return f"{var}={raw} — не читается ({e.strerror or e})"
        if empty:
            # Раннер отдаёт пустой файл как незаданный, и это ровно тот
            # случай, ради которого модуль написан: переменная стоит, галочка
            # у человека стоит, способности нет.
            return f"{var}={raw} — файл пуст"

    return ""


def state(env: dict) -> list[dict]:
    """Все способности с ответом «включена или нет» и причиной."""
    out = []
    for cap in CAPABILITIES:
        why = reason(cap, env)
        out.append({**cap, "включена": not why, "причина": why})
    return out


def disabled(env: dict) -> list[dict]:
    return [c for c in state(env) if not c["включена"]]


def lines(caps: list[dict]) -> list[str]:
    """Строки списка, выровненные по самой длинной способности. Выравнивание
    не украшение: причина справа читается колонкой, а не ищется в тексте."""
    if not caps:
        return []
    width = max(len(c["способность"]) for c in caps)
    def right(c: dict) -> str:
        if c.get("причина"):
            return c["причина"]
        # У выключателя «включена» — это состояние по умолчанию, и писать
        # «переменная задана» про незаданную переменную нельзя: соврём в
        # мелочи ровно там, где обещали не врать.
        return "включена" if c["вид"] == SWITCH else f"{c['переменная']} задан"

    return [f"{c['способность']:<{width}}  — {right(c)}" for c in caps]


def report(env: dict, show_all: bool = False) -> list[str]:
    """Готовый вывод — списком строк, чтобы его можно было и напечатать, и
    проверить тестом.

    Короткая форма (её печатает установщик) — строка на способность: он
    говорит по ходу установки, и абзац на каждую выключенную способность там
    никто не прочтёт. Подробная (`--all`) — для человека, который пришёл
    разбираться: она добавляет цену молчания и перечисляет включённое, чтобы
    список читался как состояние инсталляции, а не как список претензий.
    """
    off = disabled(env)
    out: list[str] = []
    if off:
        out.append("выключено:")
        for cap, line in zip(off, lines(off)):
            out.append("  " + line)
            if show_all:
                out.append("      " + cap["цена"])
        out.append("Выключено по решению — это норма; строка выше нужна, чтобы "
                   "это было видно, а не молчало.")
    else:
        out.append("выключенных способностей нет")
    if show_all:
        on = [c for c in state(env) if c["включена"]]
        out.append("")
        out.append(f"включено ({len(on)}):" if on else "включённых способностей нет")
        out += ["  " + s for s in lines(on)]
        # Честная граница списка: по файлу окружения видно, что переменная
        # задана, — но не видно, поднялся ли названный класс и отвечает ли
        # хостинг. Написать здесь «работает» значило бы изобразить проверку,
        # которой не было.
        out.append("«задан» — переменная на месте; поднялась ли реализация, "
                   "видно в журнале приёма.")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--env-file", default="",
                    help="файл окружения инсталляции; без него берётся окружение процесса")
    ap.add_argument("--all", action="store_true",
                    help="подробно: и включённые, и чем оборачивается каждое выключенное")
    args = ap.parse_args(argv)
    env = read_env(Path(args.env_file)) if args.env_file else dict(os.environ)
    for line in report(env, show_all=args.all):
        print(line)
    # Выключенное — не ошибка. Ненулевой код здесь означал бы «установка не
    # удалась» и вернул бы нас ровно к тому, из-за чего список и появился:
    # человек стал бы выключать способности молча, лишь бы установщик был
    # зелёным.
    return 0


if __name__ == "__main__":
    sys.exit(main())
