"""Общие условия прогона: набор не должен зависеть от хозяйства хоста.

Хозяйство приезжает двумя путями, и оба здесь снимаются: настройки
инсталляции из окружения (ниже) и хранилище токенов личностей с диска
(дальше по файлу). Оба снимаются ради одного: прогон на машине, где фабрика
РАБОТАЕТ, обязан давать то же, что прогон в CI, где не работает ничего.

## Настройки инсталляции из окружения

Сессия агента наследует окружение юнита раннера, а в нём — вся настройка
живой инсталляции: `CORE_CHECK_INTERVAL_SEC`, `AGENT_*`, ключи, адреса,
секреты. Код фабрики читает эти переменные — в том числе НА ИМПОРТЕ модуля,
— поэтому набор в такой сессии ведёт себя иначе, чем в CI:

* `agent_factory/updater.py` на импорте берёт `CORE_CHECK_INTERVAL_SEC`
  (у client-b — `3600`), и `test_watch_is_off_unless_an_interval_is_given`
  зовёт `watch(0)`, где `every = interval_sec or CHECK_INTERVAL_SEC` даёт
  3600 и `while True` крутится, пока прогон не снимут по бюджету. Это не
  «медленно», это прогон, который не заканчивается вовсе;
* `test_telegram.py::test_without_anywhere_to_write_there_is_no_feed` и
  `test_runner.py::test_verify_session_gets_a_smaller_budget` падают от
  `AGENT_PEOPLE_MAP` и `AGENT_VERIFY_TIMEOUT_SEC`: тесты снимают
  monkeypatch'ем перечисленный у себя список переменных, и всё, чего в
  списке нет, просачивается из живого окружения.

Обходилось это раньше рецептом в CLAUDE.md — снять переменные по префиксам
руками перед запуском. Рецепт работал ровно до первого раза, когда его
забыли, и стоил каждой сессии одного зависшего прогона. Поэтому снимает их
теперь сам набор, на импорте `conftest.py` — то есть ДО того, как
импортируются модули кода и застывают их константы уровня модуля.

Тесту, которому переменная нужна, она нужна СВОЯ: `monkeypatch.setenv` внутри
теста никуда не делся и работает как раньше. Здесь снимается только то, что
пришло от инсталляции.

## Хранилище токенов личностей с диска

`personas.keys_from_env(env)` берёт окружение аргументом, но последней
строкой подмешивает `keys_from_store()`, а тот читает файл С ДИСКА:
`$AGENT_LINEAR_TOKENS`, а без переменной — `~/.config/linear-agents/tokens.json`.
На машине, где фабрика работает, этот файл ЕСТЬ и полон живых ключей. Поэтому
тест, который передал свои две переменные и ждёт ровно их, получал пять чужих
настоящих — и падал. В CI файла нет, там те же тесты зелёные.

Расхождение стоило дороже самих падений: набор был красным весь день, и
красноту перестали читать — перед каждым мержем глазами сверяли, «те ли пять».
Живые `lin_oauth_…` при этом печатались в вывод pytest целиком.

Отсюда правило прогона: хранилище токенов для тестов НЕ СУЩЕСТВУЕТ, если тест
не завёл своё. Путь ведёт в пустой временный каталог, файла по нему нет, и
`keys_from_store` честно возвращает пусто — ровно как в CI. Тесту, которому
хранилище нужно (`test_linear_tokens.py`), достаточно выставить
`AGENT_LINEAR_TOKENS` у себя: его `monkeypatch.setenv` выполняется позже и
перекрывает этот.
"""
import os

import pytest

# Приставки переменных, которыми настраивается инсталляция. Список собран по
# файлу окружения живого раннера (72 переменные) и покрывает его целиком.
# Переменных самого питона, pytest и оболочки здесь нет: снимается настройка
# фабрики, а не окружение процесса.
INSTALLATION_ENV_PREFIXES = (
    "AGENT_", "BRANCH_CHECK_", "BUILD_", "CORE_", "DEPLOY_", "INTAKE_",
    "LINEAR_", "NOTIFY_", "REDIS_", "SIGNING_", "TELEGRAM_", "TRACKER_",
)

# Настройки инсталляции без общей приставки — поимённо.
INSTALLATION_ENV_NAMES = ("CLAUDE_CONFIG_DIR",)


def _снять_настройки_инсталляции() -> list[str]:
    """Убрать настройку живой инсталляции из окружения прогона.

    Зовётся на импорте, а не фикстурой, намеренно: модули кода читают часть
    переменных на импорте (`updater.CHECK_INTERVAL_SEC`), а импортируются они
    позже conftest. Фикстура опоздала бы ровно на ту переменную, из-за
    которой прогон и зависает.
    """
    снято = [name for name in list(os.environ)
             if name.startswith(INSTALLATION_ENV_PREFIXES)
             or name in INSTALLATION_ENV_NAMES]
    for name in снято:
        del os.environ[name]
    return снято


REMOVED_INSTALLATION_ENV = _снять_настройки_инсталляции()


@pytest.fixture(scope="session")
def _хранилища_токенов_нет(tmp_path_factory):
    """Один путь на весь прогон; каталог пустой, файла по пути нет."""
    return tmp_path_factory.mktemp("нет-хранилища-токенов") / "tokens.json"


@pytest.fixture(autouse=True)
def _без_живых_ключей_личностей(monkeypatch, _хранилища_токенов_нет):
    monkeypatch.setenv("AGENT_LINEAR_TOKENS", str(_хранилища_токенов_нет))
