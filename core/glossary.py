# Разметка не лезет внутрь блоков кода: там код — это код, а не слово для
# человека, и скобка посреди команды ломает саму команду.
_FENCE = re.compile(r"```.*?```|~~~.*?~~~", re.S)
_INLINE_LIMIT = 300


def _keys() -> list[str]:
    """Ключи от длинного к короткому: `FAIL/implementation` обязан обойти
    `FAIL`, иначе длинный код получит расшифровку короткого."""
    return sorted(HUMAN, key=len, reverse=True)


def explain(code: str) -> str:
    """Человеческая фраза для машинного слова. Пусто — слова нет в реестре."""
    return HUMAN.get((code or "").strip(), "")


@lru_cache(maxsize=1)
def _pattern() -> re.Pattern:
    """Собирается один раз: `codes_in` зовёт её на каждый кусок текста между
    блоками кода, а `decorate` — на каждый комментарий раннера."""
    parts = []
    for key in _keys():
        esc = re.escape(key)
        parts.append(f"`{esc}`")
        if key in BARE_OK:
            parts.append(rf"(?<![`\w]){esc}(?![`\w])")
    return re.compile("|".join(parts))


def codes_in(text: str) -> list[str]:
    """Машинные слова из реестра, которые в этом тексте есть. По одному разу,
    в порядке появления. Блоки кода не считаются: там слово адресовано
    оболочке, а не человеку."""
    out: list[str] = []
    for chunk in _FENCE.split(text or ""):
        for m in _pattern().finditer(chunk):
            code = m.group(0).strip("`")
            if code not in out:
                out.append(code)
    return out


def decorate(text: str) -> str:
    """Тот же текст, но у первого вхождения каждого кода стоит расшифровка.

    Первого — а не каждого: вердикт `FAIL/implementation` в длинном разборе
    встречается десяток раз, и десять одинаковых скобок читаются как помеха,
    а не как помощь.

    Уже расшифрованное не расшифровывается второй раз: если фраза из реестра
    стоит в тексте рядом с кодом (человек или сессия написали её сами),
    разметка молчит. Иначе комментарий, собранный из другого комментария,
    копил бы скобки на каждом круге.
    """
    if not text:
        return text
    done: set[str] = set()
    pattern = _pattern()

    def one(m: re.Match) -> str:
        whole = m.group(0)
        code = whole.strip("`")
        human = HUMAN.get(code, "")
        if not human or code in done:
            return whole
        done.add(code)
        tail = m.string[m.end():m.end() + _INLINE_LIMIT]
        if human[:40] in tail:
            return whole
        return f"{whole} ({human})"

    out: list[str] = []
    pos = 0
    for fence in _FENCE.finditer(text):
        out.append(pattern.sub(one, text[pos:fence.start()]))
        out.append(fence.group(0))
        pos = fence.end()
    out.append(pattern.sub(one, text[pos:]))
    return "".join(out)


# Разметка, навешенная `decorate`: код, пробел, фраза из реестра в скобках.
# Нужна, чтобы её можно было СНЯТЬ — см. `undecorate`.
_EXPLAINED = re.compile(
    r" \((?:" + "|".join(re.escape(v) for v in sorted(HUMAN.values(), key=len,
                                                      reverse=True)) + r")\)")


def undecorate(text: str) -> str:
    """Тот же текст без расшифровок, навешенных `decorate`.

    Не косметика. Извлекатели ищут коммит и номер MR в ПЕРВЫХ 500 знаках
    комментария — окно узкое нарочно, иначе семь шестнадцатеричных знаков
    найдутся в любом длинном разборе. Разметка добавляет к каждому коду по
    полсотни знаков, и три кода в шапке сдвигают всё, что ниже, за это окно:
    коммит, названный в четвёртой строке, перестал бы находиться. Поэтому
    машина читает текст без разметки, а человек — с ней.

    Снимается только своё: скобка с фразой ИЗ РЕЕСТРА. Чужие скобки в тексте
    сессии не трогаются.
    """
    return _EXPLAINED.sub("", text or "")


def unexplained(codes) -> list[str]:
    """Машинные слова, которых нет в реестре. Это и есть ворота.

    Зовётся тестом по настоящим источникам — классам вердиктов в контрактах и
    исходам сессии в раннере, — а не по списку, переписанному руками: список
    протух бы ровно там же, где протухает документация.
    """
    return sorted({c for c in codes if c and c not in HUMAN})


def lint_text(text: str, where: str) -> list[str]:
    """Машинные слова в тексте, у которых рядом нет расшифровки.

    Промах на слово, а не один общий: сессия чинит конкретную строку. Ищется
    только то, что реестр знает, — выдумывать расшифровку за человека модуль
    не умеет, а ругаться на незнакомое слово значило бы ругаться на любое
    имя собственное в отчёте.
    """
    misses: list[str] = []
    for code in codes_in(text):
        human = HUMAN[code]
        if human[:40] in text:
            continue
        misses.append(f"в `{where}` машинное слово `{code}` стоит без "
                      f"человеческой расшифровки — рядом с ним должно быть "
                      f"«{human}»")
    return misses


# Какие коды показать сессии прямо в контракте. Не весь реестр: контракт
# читает рабочая и проверяющая сессия, и им нужны классы вердикта, а не
# коды возврата ворот. Полный реестр — в `HUMAN` выше.
RULE_CODES = ("OK", "FIXED", "FAIL/specification", "FAIL/implementation",
              "FAIL/unobservable", "PARTIAL", "PARTIAL НЕЧЕГО",
              "PARTIAL/specification")

_RULE = """\
{i}**Ни одного машинного слова без человеческой расшифровки рядом.** Класс
{i}вердикта, исход сессии, код возврата ворот, имя метки — человек читает их
{i}как шум и идёт спрашивать, что это значит. Код НЕ выкидывай: по нему
{i}считают статистику и по нему тебя читает следующая сессия. Ставь фразу
{i}рядом, в том же месте:

{table}

{i}Правило шире таблицы: любое машинное слово, доехавшее до человека, обязано
{i}иметь расшифровку там же. Своего кода в таблице не нашёл — напиши фразу
{i}сам, одной строкой, и заведи задачу на то, чтобы он попал в реестр
{i}(`core/glossary.py`): код без расшифровки до человека доезжать не должен
{i}вообще.
"""


def rule_block(indent: str = "   ") -> str:
    """Правило расшифровки с таблицей — для контрактов всех ролей.

    Таблица собирается из `HUMAN`, а не переписана прозой: реестр один, и
    контракт обязан показывать сессии ровно то, чем раннер потом размечает
    комментарии. Появился новый класс — он появляется и здесь, сам.
    """
    table = "\n".join(f"{indent}* `{c}` — {explain(c)}" for c in RULE_CODES)
    return _RULE.format(i=indent, table=table)


def readers_block(indent: str = "   ") -> str:
    """Таблица «что чем читается» словами — для контрактов и документации.

    Одна на все места, где она нужна: разъехавшиеся копии этой таблицы и есть
    тот способ ослепить агента, ради которого она заведена.
    """
    rows = [f"{indent}| поле | кто читает | чем извлекается |",
            f"{indent}| -- | -- | -- |"]
    for what, who, how in READERS:
        rows.append(f"{indent}| {what} | {who} | {('`' + how + '`') if how else '—'} |")
    return "\n".join(rows)


# Машинные артефакты сессии: имя файла → зачем он и кому.
ARTIFACTS: tuple[tuple[str, str], ...] = (
    ("expected.md", "эталон проверки, записанный ДО чтения чужих слов"),
    ("gates.json", "журнал ворот: что запускали, с каким кодом, чем это считается"),
    ("plan.md", "решение по шлюзу тяжёлой задачи"),
    ("handoff.md", "сдача работы по схеме"),
    ("review.md", "код-ревью диффа"),
    ("verdict.txt", "вердикт проверки одной строкой"),
    ("transcript.jsonl", "полный ход сессии"),
)


def machine_part(workdir) -> str:
    """Где лежит машинная часть. Пусто — каталога нет или он пуст.

    Дополнение владельца (DEV-108, 16.09) просило разделить поверхности:
    Linear — человеку, машинная передача — по ссылке, и **ничего не удалять**.
    Удалить здесь и правда нельзя: `expected.md`, журнал ворот и транскрипт —
    то, чем спорят, когда два вердикта разошлись, и то, что читает следующая
    сессия.

    Поэтому — не ссылка наружу, а адрес: хост фабрики не отдаёт файлы в сеть,
    и честнее назвать путь, по которому они лежат, чем сделать вид, что у них
    есть URL. Блок короткий и стоит последним: человек его пролистывает, а
    тот, кому он нужен, знает, что искать.
    """
    root = Path(workdir) if workdir else None
    if not root or not root.is_dir():
        return ""
    rows = [f"`{name}` — {why}" for name, why in ARTIFACTS if (root / name).exists()]
    if not rows:
        return ""
    return ("**Машинная часть** (человеку читать не нужно, следующей сессии и "
            f"спору — нужно): {'; '.join(rows)}. Всё это лежит в рабочем "
            f"каталоге `{root}` на хосте фабрики.")
