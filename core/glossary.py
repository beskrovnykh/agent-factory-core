"""Расшифровка машинных слов (DEV-108): рядом с кодом — человеческая фраза.

Владелец читает `FAIL/specification` и идёт спрашивать, что это значит. Для
машины это точный класс расхождения, по которому считается статистика и
выбирается маршрут задачи; для человека — шум, за которым спрятан ответ
«задача слишком крупная, иди дроби». Оба читателя правы, и текст у них один.

Отсюда правило, которое держит этот модуль: **любое машинное слово,
доезжающее до человека, обязано иметь человеческую расшифровку в том же
месте.** Не вместо кода — рядом с ним: код нужен следующей сессии и счёту,
фраза нужна человеку, и выкинуть можно только одного из двух читателей.

Здесь три вещи, и они нарочно в одном файле:

* `HUMAN` — сам реестр «машинное слово → фраза». Один на всю фабрику.
* `decorate` — разметка готового текста: первое вхождение каждого кода
  получает расшифровку в скобках. Ею раннер размечает КАЖДЫЙ комментарий,
  который кладёт сам.
* `unexplained` — ворота. Новый код без записи в реестре роняет набор, и это
  не договорённость, а падающий тест (`test_glossary.py`).

Почему ворота, а не список в документации: список протухает на первом же
новом классе, и протухание никак не видно — код едет к человеку голым ровно
так же, как ехал до этой задачи.

Отдельно — `READERS`: кто что читает. Без него «почистили для человека»
превращается в «выбросили то, чем жил следующий агент»: комментарии в Linear
читают не только люди, и проверка достаёт из заявки автора коммит, ветку и
прошлый вердикт.
"""
