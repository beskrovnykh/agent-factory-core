"""Шапка машинного комментария (DEV-108): ответ раньше доказательства.

До этого модуля комментарий каждой роли открывался доказательством. Отчёт
работы начинался с `## Цель`, вердикт проверки — с позиций подстрок в промпте
и сумм `md5`, ревью — со списка находок. Материал верный, но он написан для
спора, а человек приходит не спорить: ему надо решить, что делать дальше.

На DEV-41 это померили: восемь машинных комментариев, больше 33 000 знаков,
три круга проверки — и владелец, поставивший задачу, не смог ответить ни на
«что сделано», ни на «как этим воспользоваться». Подробности стояли ВМЕСТО
ответа; должны — после него.

**Шапка — два-три предложения обычного текста.** Не бланк с подписями к
полям. Первый заход по этой задаче сделал как раз бланк:

    **Что требуется от человека** — мержить
    **Что сделано** — ворота проверки стали строже на две пропущенные вещи
    **Как посмотреть самому** — `knowledge.py audit`, ждём «не хватает: 0»
    **Итог** — прошло

и владелец вернул работу дословно так: «Я не хочу машинерию, опять эти
какие-то списки, какие-то непонятные. Не хочу трафареты. Нормальное общение,
как люди общаются». Он прав и по делу: пять жирных подписей ничем не лучше
`FAIL/specification` — тот же машинный язык, только с переводом. Человек
такой текст не читает, а сканирует.

Как надо — его же пример:

    Сделал ворота проверки строже — теперь ловят две вещи, которые раньше
    проскакивали. Посмотреть можно командой `knowledge.py audit`, должна
    сказать «не хватает: 0». Всё сошлось, дальше нужен твой мерж.

Тот же смысл, сказанный, а не заполненный. Ниже — черта и всё прежнее
содержимое без сокращений: дотошность внутри проверки это ценность, чинится
только подача.

**Что здесь проверяется кодом.** «Живым языком» не проверить, и притворяться,
что проверено, нельзя. Проверяются четыре вещи, которые владелец сам назвал
признаками бланка (`lint_text`):

* шапка — абзац прозы: не заголовок, не блок кода, не список, без жирных
  подписей к полям;
* выше черты нет ни одного машинного слова из реестра (`glossary.HUMAN`) и
  ни одного служебного слова продукта («ворота», «вердикт», «исход»);
* абзац короче 400 знаков — не влезло, значит это уже подробности;
* в нём есть глагол в адрес человека либо прямая фраза, что от него ничего
  не нужно.

Ни одна из четырёх не ловит «написано сухо», и ни одна не превращается
обратно в бланк: подписи к полям запрещены прямо.

**Старый бланк остаётся читаемым, но не пишется.** `fields_of` разбирает
пятистрочную шапку по-прежнему — она уже лежит в живых задачах, и лента
заходов (`timeline.py`) собирается по тому, что там есть. Перестать её
понимать значило бы ослепить агентов на всей истории — ровно то, от чего
предостерегало дополнение владельца.

Разбор и сборка рядом нарочно: шапку и пишут сессии, и собирает раннер
(лента заходов), и разъехаться этим двум пониманиям нельзя — иначе раннер
будет требовать одно, а показывать другое.
"""
from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

import glossary
import handoff
from handoff import key_of

# Потолок абзаца. Владелец: «Коротко. Два-три предложения. Не влезло — значит
# остальное ниже черты» и отдельно — «он короче примерно четырёхсот знаков».
# Длина — единственное, чем отличается ответ от начала доказательства.
MAX_CHARS = 400

# Потолок одной фразы, собранной раннером из чужого текста (цель работы,
# вердикт проверки). Меньше абзаца: из таких фраз абзац и складывается, и
# каждая обязана оставить место соседним.
MAX_PHRASE_CHARS = 220

# Черта, ниже которой живут подробности. Не сворачивающийся блок: Linear
# показывает `---` горизонтальной линией в любом клиенте, а на `<details>`
# в комментариях полагаться нельзя — там, где он не раскрылся бы, человек
# потерял бы не шапку, а как раз доказательство.
RULE = "---"

# Слова старого бланка. Нужны для ЧТЕНИЯ комментариев, написанных до этой
# правки: они уже лежат в задачах и переписываться не будут.
FIELDS = ("Что требуется от человека", "Что сделано", "Как посмотреть самому",
          "Итог", "Чего ждать дальше")
ALIASES = {"Как воспользоваться": "Как посмотреть самому"}

MISS_NO_HEADLINE = ("нет шапки: два-три предложения обычного текста ДО любых "
                    "подробностей — что сделано, где это посмотреть самому и "
                    "что нужно от человека")

_HEADING = re.compile(r"^\s{0,3}#{1,6}\s")
_HR = re.compile(r"^\s{0,3}([-*_])(?:\s*\1){2,}\s*$")
_FENCE = re.compile(r"^\s{0,3}(?:```|~~~)")
# Маркеры списка и разметка вокруг слова: модель пишет строку и списком, и
# жирным, и через двоеточие. Терпим оформление, но не другое слово.
_BULLET = re.compile(r"^\s{0,4}(?:[-*+•]|\d{1,2}[.)])\s+")
_DECOR = re.compile(r"^[*_`\s]+|[*_`\s]+$")
_SPLIT = re.compile(r"\s*(?:—|–|:|\s-\s)\s*")

# Жирная подпись к полю — тот самый бланк: строка начинается с `**Что‑то**`,
# за которым идёт тире или двоеточие. Именно эту форму владелец и отверг,
# поэтому она названа отдельным промахом, а не ловится через «это список».
_FIELD_LABEL = re.compile(r"^\s{0,4}(?:[-*+•]\s*)?\*\*[^*\n]{2,60}\*\*\s*(?:—|–|:|-\s)")

# Служебные слова продукта. Машинные коды сюда не переписаны — они берутся из
# реестра (`glossary.HUMAN`), чтобы новый код попадал под запрет сам. Здесь
# только те слова, которые кодами не являются, а всё равно читаются как
# машинерия. `исходный`/`исходя` не ловятся нарочно — это обычные слова.
_SERVICE = (
    (re.compile(r"\bворот(а|ам|ами|ах|)\b", re.I), "ворота"),
    (re.compile(r"\bвердикт[а-яё]*\b", re.I), "вердикт"),
    (re.compile(r"\bисход(ы|ов|е|у|ом|а|ам|ами|ах)?\b", re.I), "исход"),
)

# Глагол в адрес человека. Смотреть/открыть/зайти сюда НЕ входят нарочно:
# «посмотреть можно командой» стоит почти в каждой шапке, и с ними проверка
# проходила бы вхолостую, ничего не проверяя.
_ACTION = re.compile(
    r"мерж|смерж|разбер|разобра|разбир|подтверд|дроб|разреза|разрез\b|резать|"
    r"уточн|поправ|реши(ть|)\b|решать|прим(и|ешь)\b|принять|назнач|"
    r"дай\b|дать\b|отве(ть|тить)|скаж(и|ешь)|подскаж|выбер|выбра|закр(ой|ыть)",
    re.I)

# …либо прямая фраза, что человек тут не нужен. Отдельным набором, а не
# отрицанием: «ничего» в шапке встречается и в других смыслах («ничего не
# сломалось»), и по одному слову это не отличить.
_NOTHING = re.compile(
    r"от теб[яе]\s+(?:пока\s+)?ничего|тво(его|ей)\s+\w+\s+не\s+(нужн|требуе)|"
    r"ничего\s+(?:пока\s+)?не\s+(нужн|требуе|над)|"
    r"ничего\s+делать\s+не\s+(над|нужн)|"
    r"(?:тут|здесь|сейчас)\s+ты\s+не\s+нужен|"
    r"тво[яй]\s+рука\s+не\s+нужна|не\s+требует\s+тво",
    re.I)


_SECTION_KEYS = frozenset(key_of(s) for s in handoff.SECTIONS)


def _is_section(line: str) -> bool:
    """Заголовок раздела сдачи — не титул, а уже подробности.

    Иначе отчёт, начинающийся с `## Цель`, читался бы как «титул плюс
    шапка», и сессия получала бы возврат про слова внутри своей цели вместо
    прямого «шапки нет».
    """
    return key_of(re.sub(r"^\s{0,3}#{1,6}\s*", "", line)) in _SECTION_KEYS


def _blocks(text: str) -> tuple[str, list[str], list[str]]:
    """(титул, строки шапки, строки подробностей).

    Титул — один заголовок в самом начале, если он там есть: проверка
    открывает комментарий строкой «## Проверка DEV-41», лента — своей, и
    отнимать у них заголовок ради шапки, которая и так встанет следующей
    строкой, незачем. Титул возвращается отдельно, потому что запрет на
    машинные слова действует и на него: `## Проверка DEV-41 — FAIL` это
    ровно тот первый экран, из-за которого задача и заведена.

    Шапка — первый абзац после титула: всё до пустой строки, черты или
    следующего заголовка.
    """
    lines = text.splitlines()
    i = 0
    while i < len(lines) and not lines[i].strip():
        i += 1
    title = ""
    if i < len(lines) and _HEADING.match(lines[i]) and not _is_section(lines[i]):
        title = lines[i].strip()
        i += 1
    while i < len(lines) and not lines[i].strip():
        i += 1
    lead: list[str] = []
    while i < len(lines):
        line = lines[i]
        if not line.strip() or _HEADING.match(line) or _HR.match(line):
            break
        lead.append(line)
        i += 1
    return title, lead, lines[i:]


def lead_of(text: str) -> str:
    """Шапка одним абзацем, как её прочитает человек. Пусто — шапки нет."""
    return " ".join(l.strip() for l in _blocks(text)[1]).strip()


# ── чтение старого бланка ────────────────────────────────────────────────────

def _field_of(line: str) -> tuple[str, str]:
    """(нормализованное имя строки бланка, значение). Не строка — ("", "")."""
    body = _BULLET.sub("", line).strip()
    if not body:
        return "", ""
    parts = _SPLIT.split(body, maxsplit=1)
    if len(parts) != 2:
        return "", ""
    return key_of(_DECOR.sub("", parts[0])), _DECOR.sub("", parts[1]).strip()


def _canon(name: str) -> str:
    """Имя строки бланка к последнему его виду. Не строка бланка — пусто."""
    if not name:
        return ""
    known = {key_of(f): key_of(f) for f in FIELDS}
    known.update({key_of(old): key_of(new) for old, new in ALIASES.items()})
    return known.get(name, "")


def fields_of(text: str) -> dict[str, str]:
    """Строки СТАРОГО бланка из начала комментария. Пусто — шапка прозой.

    Только для чтения истории: новые комментарии бланком не пишутся, а старые
    лежат в живых задачах, и лента заходов собирается в том числе по ним.
    """
    _, lead, _ = _blocks(text)
    out: dict[str, str] = {}
    for line in lead:
        if not line.strip():
            continue
        name = _canon(_field_of(line)[0])
        if not name:
            break
        out.setdefault(name, _field_of(line)[1])
    return out


# ── проверка шапки ───────────────────────────────────────────────────────────

def lint_text(text: str, where: str) -> list[str]:
    """Чего не хватает шапке в этом тексте. Пусто — по схеме.

    `where` — как назвать место в возврате сессии (`handoff.md`, `review.md`,
    «комментарий с вердиктом»): сессия чинит конкретный файл, а не «шапку
    вообще».

    Промахи называются поимённо и по одному на причину: сессия должна суметь
    исправить сдачу с одного возврата, не угадывая, что именно не понравилось.
    """
    if not text.strip():
        return [f"в `{where}` {MISS_NO_HEADLINE}"]
    title, lines, rest = _blocks(text)
    lead = " ".join(l.strip() for l in lines).strip()
    if not lead:
        return [f"в `{where}` {MISS_NO_HEADLINE}"]

    misses: list[str] = []
    if any(_FIELD_LABEL.match(l) for l in lines):
        misses.append(
            f"в `{where}` шапка написана бланком: жирные подписи к полям "
            f"(**Что сделано** — …) человек не читает, а сканирует. Нужен тот "
            f"же смысл обычным текстом, два-три предложения подряд")
    elif any(_BULLET.match(l) for l in lines):
        misses.append(
            f"в `{where}` шапка написана списком — выше черты списков нет, "
            f"только сплошной текст. Списки и разделы начинаются ниже `{RULE}`")
    if _FENCE.match(lines[0]):
        misses.append(f"в `{where}` шапка начинается блоком кода — первым "
                      f"человек должен прочитать фразу, а не команду")
    if len(lead) > MAX_CHARS:
        misses.append(f"в `{where}` шапка длиннее {MAX_CHARS} знаков "
                      f"({len(lead)}) — дальше это уже подробности, их место "
                      f"ниже черты `{RULE}`")
    if not _ACTION.search(lead) and not _NOTHING.search(lead):
        misses.append(
            f"в `{where}` из шапки не видно, что делать человеку: скажи прямо "
            f"— мержить, разобрать, дробить, подтвердить — либо так же прямо, "
            f"что от него ничего не нужно")
    misses += _machine_words(title, lead, where)
    return misses


def _codes_above(text: str) -> list[str]:
    """Машинные слова выше черты — в кавычках и БЕЗ них, по одному разу.

    Реестр (`glossary.codes_in`) узнаёт без кавычек не всё: `FAIL` он в прозе
    не трогает нарочно — «ложный FAIL стоит круга» это предложение, а не
    вердикт. Выше черты такой оговорки нет: там человек, и
    `FAIL/implementation` в скобках для него ровно тот же шум, что в
    кавычках. Владелец назвал `FAIL`, `PARTIAL` и `unobservable` поимённо.
    """
    out = list(glossary.codes_in(text))
    for m in _bare().finditer(text or ""):
        code = m.group(0).strip("`")
        if code in glossary.HUMAN and code not in out:
            out.append(code)
    return out


def _machine_words(title: str, lead: str, where: str) -> list[str]:
    """Машинные и служебные слова выше черты — по промаху на слово.

    Коды берутся из реестра, а не из списка здесь: новый класс вердикта
    попадает под запрет сам, без правки этого файла. Ниже черты код нужен и
    остаётся — запрет действует ровно на первый экран.
    """
    out: list[str] = []
    for code in _codes_above(f"{title}\n{lead}"):
        human = glossary.explain(code)
        out.append(f"в `{where}` выше черты стоит машинное слово `{code}` — "
                   f"скажи это по-человечески («{human}»), а сам код оставь "
                   f"ниже черты, где его читает следующая сессия")
    for pattern, word in _SERVICE:
        if pattern.search(f"{title}\n{lead}"):
            out.append(f"в `{where}` выше черты стоит служебное слово "
                       f"«{word}» — оно из внутренней кухни; человеку скажи, "
                       f"что случилось, его словами")
    return out


def lint_file(workdir, name: str) -> list[str]:
    """То же по файлу в рабочем каталоге сессии.

    Файла нет — пусто, а не промах: отсутствие файла сдачи называет схема
    сдачи (`handoff.lint_file`), и повторять это словами шапки значило бы
    вернуть сессии два промаха на одно действие.
    """
    try:
        text = (Path(workdir) / name).read_text(errors="replace")
    except OSError:
        return []
    return lint_text(text, name)


# ── сборка ───────────────────────────────────────────────────────────────────

# Чем заменить служебное слово, приехавшее в шапку ИЗ ЧУЖОГО ТЕКСТА. Только
# для кусков, которые раннер цитирует сам (цель работы, раздел «чем
# наблюдать»): у него нет способа переписать чужую фразу, а печатать то, за
# что он вернул бы сессию, он не должен. Тексты, которые сессия пишет сама,
# через это не проходят — там промах называется словами и чинит его сессия.
# Замены с сохранением падежа: «вердикту» → «ответу», «исходом» → «результатом».
# Оба слова мужского рода с теми же окончаниями, поэтому меняется корень, а
# не целое слово — иначе в цитате получается «по ответ проверки от 16.09».
_SOFTEN_STEM = (
    # Хвост `(?:\s+проверки)?` съедается вместе с корнем: иначе из «вердикта
    # проверки» выходит «ответа проверки проверки» — слово уже несёт смысл.
    (re.compile(r"\bвердикт([а-яё]*)(?:\s+проверки)?", re.I), "ответ"),
    (re.compile(r"\bисход(ы|ов|е|у|ом|а|ам|ами|ах)?\b", re.I), "результат"),
)
# У «ворот» своей пары по окончаниям нет — падежи перечислены.
_SOFTEN_FORM = {"ворота": "проверки", "ворот": "проверок", "воротам": "проверкам",
                "воротами": "проверками", "воротах": "проверках"}
_GATES = re.compile(r"\bворот(?:а|ам|ами|ах)?\b", re.I)
def soften(text: str) -> str:
    """Служебные слова и голые коды — человеческими. Для ЦИТАТ, не для своих
    слов: раннер вставляет в шапку чужие фразы (цель работы, раздел «чем
    наблюдать») и переписать их не может, а печатать то, за что вернул бы
    сессию, не должен. Тексты, которые сессия пишет сама, сюда не попадают —
    там промах называется словами и чинит его сессия.
    """
    text = text or ""
    for pattern, stem in _SOFTEN_STEM:
        text = pattern.sub(lambda m, s=stem: s + (m.group(1) or ""), text)
    text = _GATES.sub(lambda m: _SOFTEN_FORM.get(m.group(0).lower(), "проверки"), text)
    return _bare_codes_out(text)


@lru_cache(maxsize=1)
def _bare() -> re.Pattern:
    """Любой код реестра, в кавычках или без. Длинные раньше коротких, иначе
    `FAIL` съест `FAIL/implementation`."""
    keys = "|".join(re.escape(k) for k in sorted(glossary.HUMAN, key=len,
                                                  reverse=True))
    # Границы обязательны: без них `OK` находится внутри `TOKEN`, а `FAIL` —
    # внутри `FAILOVER`, и шапка возвращалась бы сессии за слово, которого в
    # ней нет. Слэш в границу входит, иначе `FAIL` откусывался бы от
    # `FAIL/implementation` раньше, чем тот успеет совпасть целиком.
    return re.compile(rf"`(?:{keys})`|(?<![\w/`])(?:{keys})(?![\w/`])")


def _bare_codes_out(text: str) -> str:
    """Код в цитате — человеческой фразой. В отличие от `glossary.humanize`
    берёт и голые коды: выше черты кавычки ничего не меняют."""
    def one(m: re.Match) -> str:
        human = glossary.explain(m.group(0).strip("`"))
        if not human:
            return m.group(0)
        head = m.string[:m.start()].rstrip()
        return human[0].upper() + human[1:] if not head or head[-1] in ".!?…" else human
    return _bare().sub(one, text)


def render(*, done: str, use: str, act: str, title: str = "") -> str:
    """Шапка текстом — для комментариев, которые собирает раннер сам.

    Три куска, и каждый — ЗАКОНЧЕННОЕ предложение, а не значение поля: из
    значений собирается бланк, из предложений — абзац. Поэтому и по именам,
    а не по порядку: позиционный вызов однажды уже подставил бы одно в
    другое молча.

    `done` — что произошло; `use` — где человек увидит это своими глазами;
    `act` — что нужно от него (или что не нужно). Порядок именно такой:
    владелец просил «сначала то, что человеку делать», но его же примеры
    ставят действие последним, и последнее предложение абзаца из трёх — это
    и есть то, с чем человек уходит. Проверка (`lint_text`) требует действия
    в абзаце, а не в первой фразе, — тем и снято противоречие.

    Обрезка по потолку здесь тоже есть: куски приезжают из чужого текста
    (цель работы, отчёт прошлого захода), и раннер не должен уметь положить
    в шапку то, за что вернул бы сессию.
    """
    def one(value: str, limit: int = MAX_PHRASE_CHARS) -> str:
        value = " ".join(soften(value or "").split())
        # Обрезка чужой фразы оставляет пробел перед знаком: «…кодом :».
        value = re.sub(r"\s+([,.;:!?…])", r"\1", value)
        if len(value) > limit:
            value = value[:limit - 1].rstrip() + "…"
        if value and value[-1] not in ".!?…":
            value += "."
        return value

    # Потолок у АБЗАЦА, а не у куска: три куска по своему потолку складывались
    # в шапку длиннее той, за которую раннер вернул бы сессию. Место делится в
    # пользу действия — ради него абзац и пишется, — а режутся «что сделано» и
    # «где посмотреть», и то не короче шестидесяти знаков: обрубок в три слова
    # не отвечает ни на что.
    said = one(act)
    room = max(60, (MAX_CHARS - len(said) - 2) // 2 - 1)
    body = " ".join(p for p in (one(done, room), one(use, room), said) if p)
    return (f"{title}\n\n{body}" if title else body)


def with_details(headline: str, details: str) -> str:
    """Шапка, черта, подробности — в этом порядке и без сокращения подробностей."""
    details = (details or "").strip()
    if not details:
        return headline.strip()
    return f"{headline.strip()}\n\n{RULE}\n\n{details}"


