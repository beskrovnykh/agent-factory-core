_SCHEMA = """\
{i}Два-три предложения подряд, обычным текстом. Без жирных подписей к полям,
{i}без списка, без заголовка, без слова «итог». В них должно поместиться:

{i}* что сделано — одной фразой, без имён файлов;
{i}* как человеку посмотреть это самому — место или команда, прямо внутри
{i}фразы, а не отдельной строкой-полем; нечего пока смотреть — так и скажи;
{i}* что нужно от человека — мержить, разобрать, дробить, подтвердить. Если
{i}не нужно ничего, скажи это прямо: «от тебя ничего не нужно».

{i}Вот как это выглядит, когда работа сделана:

{i}> Сделал проверку строже — теперь ловит две вещи, которые раньше
{i}> проскакивали. Посмотреть можно командой `knowledge.py audit`, должна
{i}> сказать «не хватает: 0». Всё сошлось, дальше нужен твой мерж.

{i}Когда взяться не вышло:

{i}> Не могу взять в работу: задача слишком крупная. Это шесть отдельных
{i}> механизмов, а ветка делает один из них. Нужно разрезать на части,
{i}> тогда возьму.

{i}Ни одного машинного слова выше черты: не `FAIL/specification`, а «задача
{i}слишком крупная — резать или уточнять»; не «тесты прошли ворота», а
{i}«тесты на ветке зелёные». Коды нужны следующей сессии — они остаются, но
{i}НИЖЕ черты, вместе с остальными подробностями."""


def schema_block(indent: str = "   ") -> str:
    """Схема шапки словами — одна на контракты всех ролей, которые её пишут
    (работа, ревью, проверка, дежурный), и на возврат сессии, чтобы в
    возврате сессия видела то же, что читала в постановке."""
    return _SCHEMA.format(i=indent)


_WHY = """\
{i}Человек, который открывает задачу, приходит не спорить с тобой, а решить,
{i}что делать дальше. Первым он читает то, что стоит первым, — и если там
{i}позиции подстрок и суммы `md5`, он не отвечает ни на один свой вопрос и
{i}зовёт тебя переводить с машинного. На DEV-41 так и вышло: восемь машинных
{i}комментариев, 33 000 знаков, и постановщик не смог понять ни что сделано,
{i}ни как этим воспользоваться.

{i}Заполненный бланк тут не помогает: пять жирных подписей человек так же
{i}сканирует и так же раздражается. Пиши, как написал бы живому человеку,
{i}который платит за эту работу и не знает твоих слов.

{i}Подробности не сокращай — они ниже черты, целиком. Дотошность внутри
{i}проверки это ценность; чинится только порядок: ответ раньше доказательства.

{i}**Комментарий в задаче читают не только люди.** Проверяющая сессия достаёт
{i}из твоей сдачи коммит, ветку и заявку; лента заходов — роль и чем кончился
{i}заход; приём — раздел «Цель». Всё это лежит НИЖЕ черты, и ничего не
{i}удаляется: человеческая шапка у машины не отнимает ничего. Что чем
{i}читается:

{readers}

{rule}"""


def why_block(indent: str = "   ") -> str:
    """Зачем шапка и почему подробности не сокращаются — для контрактов.

    Одним куском на все роли: правило машинных слов и таблица читателей нужны
    и работе, и проверке, а две копии этого текста разъехались бы на первой
    же правке — ровно как разъезжаются копии схемы.
    """
    return _WHY.format(i=indent, readers=glossary.readers_block(indent),
                       rule=glossary.rule_block(indent))


_VERDICT = """\
{i}ШАПКА, и она первой. Любой твой комментарий в задачу — сошлось или нет —
{i}открывается двумя-тремя предложениями обычного текста, ДО построчной
{i}сверки и до любых подробностей. Без имён файлов, без позиций подстрок,
{i}без сумм `md5`: этот абзац человек читает первым и по нему решает, что
{i}делать дальше.

{schema}

{i}Для проверки в эти два-три предложения помещается: что ты смотрел и чем;
{i}где человек увидит то же своими глазами (дверь стенда, команда, место в
{i}журнале); чем кончилось и что теперь нужно от него — мержить, разбирать,
{i}дробить постановку или ничего. Той же фразой скажи, придёт ли сюда ещё
{i}кто-нибудь сам или задача встала и ждёт человека: он не должен это
{i}угадывать. Потом черта `---`, и всё остальное ниже неё, целиком и без
{i}сокращений.

{i}Класс расхождения при этом никуда не девается — он переезжает под черту,
{i}ПЕРВОЙ её строкой, отдельной и машинной:

{i}    **Вердикт:** `FAIL/implementation`

{i}Её читает раннер и следующая сессия (`timeline.verdict_of`), поэтому
{i}напиши её ровно так, одним из классов шага 9. А титул комментария — тот,
{i}что над шапкой, — пиши по-человечески: «## Проверка DEV-41 до мержа
{i}(коммит `abc1234`, PR #54) — сошлось». Коммит и номер PR из титула не
{i}убирай: по ним следующая проверка узнаёт, этот ли код уже смотрели.

{i}Не сошлось — абзац такой же человеческий: «Проверил на стенде, заявленного
{i}поведения не увидел: вместо X пришло Y. Вернул агенту, тебе делать ничего
{i}не нужно». Класс расхождения и построчная сверка — ниже черты.

{why}
"""


def verdict_block(indent: str = "   ") -> str:
    """Шапка вердикта словами — одна на все исходы проверки.

    Собирается до исходов, чтобы прошедшая проверка и провал открывались
    одинаково: человек не должен по виду шапки догадываться, чем кончилось,
    — это сказано в ней самой.
    """
    return _VERDICT.format(i=indent, schema=schema_block(indent),
                           why=why_block(indent))
