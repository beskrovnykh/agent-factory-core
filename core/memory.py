"""Три слоя памяти сессии и их владельцы (DEV-43).

Слоёв три, и путать их нельзя — у каждого свой владелец, то есть свой ответ
на вопрос «кто эту запись правит и что с ней будет при обновлении продукта»:

| слой | владелец | где физически | как меняется |
|------|----------|---------------|--------------|
| проект | клиент | `AGENT_MEMORY_STORE/agent-<роль>/` | нарабатывают сессии по ходу |
| методология | продукт | база — рядом с этим файлом (`methodology/`) | приезжает с релизом |
| человек | владелец процесса | `AGENT_PERSON_MEMORY` | правит он сам |

Почему это не один стор с тремя подкаталогами: стор инсталляции отдаётся
клиенту. Всё, что лежит внутри него, клиент вправе читать, править и увезти с
собой. Привычки владельца процесса туда не помещаются по смыслу (это его
личное знание, переносимое между ЕГО проектами), а методология — по владению:
её правит релиз продукта, а не команда клиента. Разделение только именем
каталога этого не давало — оттуда и невозможность отдать стор.

**Пишет сессия ровно в один слой — проектный.** Методология и слой о человеке
приезжают на чтение: их индекс кладётся в промпт, файлы сессия читает с диска
по абсолютному пути, когда запись оказалась ей нужна.

Переопределение вместо правки
-----------------------------
Клиент не редактирует файл методологии, а кладёт поверх свой С ТЕМ ЖЕ ИМЕНЕМ
в `AGENT_MEMORY_STORE/methodology/`. Склейка — **целым файлом**, не по
разделам и не построчно, и это решение, а не упрощение:

* по разделам склейка требует, чтобы структура базового файла была
  контрактом. Релиз переименовал заголовок — переопределение либо не легло
  никуда, либо легло вторым разделом рядом. Молча, потому что проверить
  «попало ли» без базы нельзя;
* построчно — то же самое в худшем виде: это трёхсторонний мерж внутри файла,
  и решать конфликты некому — установщик не человек с редактором;
* целым файлом переопределение не конфликтует НИКОГДА. Худший исход —
  устаревший файл клиента, и он виден: в промпте запись помечена как
  переопределённая, а база лежит рядом целой.

Убрать пункт базовой методологии тоже можно переопределением: файл клиента с
`drop: true` во frontmatter. Пустой файл этого НЕ значит — иначе оборванная
запись молча выключала бы правило.

Потолок чтения
--------------
В контекст грузится индекс, а не стор. Индексов теперь три, и сложение — та
самая опасность, о которой предупреждал DEV-29 (у живого стора индекс был
19.5 КБ при потолке чтения 24.4 КБ). Поэтому потолок ОДИН на все три слоя
(`budget`), и делится он так:

1. индекс проектного слоя берёт столько, сколько занимает — его пишет сама
   сессия, и урезать чужие записи мы не вправе;
2. остаток отдаётся методологии — она обязательство продукта;
3. что осталось после неё — слою о человеке.

Не поместившееся не пропадает молча: на месте обрезанного хвоста стоит
строка «ещё N записей» с путём к каталогу. А если проектный индекс съел
потолок целиком, сессия получает прямое указание сжать его — это единственный
слой, который она вправе править.

Потолок считает СТРОКИ ЗАПИСЕЙ — то, что растёт с работой. Пояснения к слоям
(заголовки ниже) и строка про обрезанный хвост в бюджет не входят: их пара
килобайт одинакова у любой инсталляции и не меняется со временем, а резать их
значило бы выдать сессии список без правила, по которому его читать, — или
обрезать слой, ничего об этом не сказав.
"""
from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path

log = logging.getLogger("agent-runner")

# База методологии едет с продуктом и лежит рядом с этим модулем — и в
# репозитории, и на хосте после раскатки (install.sh кладёт `core/methodology`
# в HOME_DIR). Путь от себя, а не константой, по той же причине, что у
# LOGDIFF_PATH в prompt.py: захардкоженный `/home/ubuntu/agent-runner/`
# разъехался бы с реальностью на первом переезде каталога.
METHODOLOGY_BASE = Path(__file__).resolve().parent / "methodology"

# Имена, которые в каталоге слоя записями НЕ считаются: индекс проектного слоя
# и пояснительная записка, которую установщик кладёт в каталог переопределений.
NOT_ENTRIES = {"MEMORY.md", "README.md"}

# Потолок на все три индекса вместе, в байтах. 12 КБ — половина наблюдавшегося
# потолка чтения (24.4 КБ, DEV-29): вторая половина остаётся под CLAUDE.md
# репозитория и сам контракт сессии, они тоже грузятся в контекст.
DEFAULT_INDEX_MAX = 12000
# Броня методологии: сколько байт потолка она получает ВСЕГДА, сколько бы ни
# занимал проектный индекс.
#
# До 14.09.2026 проектный индекс списывался с потолка первым, а методология
# получала остаток — и уходила под нож первой, хотя она мала (шесть правил,
# ~2.2 КБ), одинакова для всех инсталляций и нужнее всего именно тогда, когда
# проектный слой распух. Роль проверки на client-b не видела `definition-of-done`
# с 12.09: её индекс дорос до 16 КБ, и методологии не досталось ничего. Роль,
# которая сверяет работу с определением готовности, четверо суток проверяла по
# тому, что придумала сама.
METHODOLOGY_FLOOR = 4000

# Вид записи. Поле `kind` во frontmatter; пусто — вид неизвестен.
#
# Зачем вид вообще: порядок обрезки индекса был АЛФАВИТНЫМ (`sorted(glob)` плюс
# `_fit` по порядку). `definition-of-done.md` выживал потому, что «d» третья из
# шести, а не потому, что это определение готовности. Типо-слепое сжатие
# сохраняет 53% ограничений после одного прохода и 10% после пяти — лечится
# только тем, что у ограничения есть признак, по которому его можно не резать.
CONSTRAINT_KIND = "ограничение"

# Жёсткая полоса ограничений: сколько байт они забирают из раздела ПЕРВЫМИ,
# сколько бы записей ни стояло за ними по алфавиту.
#
# Полоса ограничена, а не бесконечна, по той же причине, по которой вообще есть
# потолок: «ограничений не бывает много» — договорённость, а не механизм, и
# инсталляция, написавшая их сто, не должна тихо съесть весь контекст. Что не
# влезло даже в полосу — названо вслух отдельной строкой, потому что это не
# нормальная обрезка, а промах раскладки.
CONSTRAINT_BAND = 3000

@dataclass(frozen=True)
class Entry:
    """Одна запись памяти: строка индекса и файл, который сессия прочитает."""
    name: str
    description: str
    path: Path
    dropped: bool = False        # выключена переопределением (`drop: true`)
    overridden: bool = False     # база перекрыта файлом клиента
    kind: str = ""               # вид записи (`kind:`), см. CONSTRAINT_KIND
    track: str = ""              # дисциплина (`track:`), см. applies_to_tracks
    roles: tuple[str, ...] = ()  # кому адресована (`roles:`), см. applies_to_role

    @property
    def is_constraint(self) -> bool:
        return self.kind.strip().lower() == CONSTRAINT_KIND

    def line(self) -> str:
        """Строка индекса. Путь АБСОЛЮТНЫЙ: слой лежит вне каталога памяти
        сессии, относительное имя файла ей не открыть."""
        mark = " [переопределено клиентом]" if self.overridden else ""
        desc = f" — {self.description}" if self.description else ""
        return f"- {self.name}{desc}{mark} ({self.path})"


def entry_of(path: Path) -> Entry:
    """Запись из frontmatter файла. Нет frontmatter → имя по файлу, без описания.

    Незакрытый frontmatter (нет `---` после начала) читается как отсутствующий:
    иначе строка «name:» из прозы в теле подменила бы имя записи.
    """
    name, desc, dropped, kind, track = path.stem, "", False, "", ""
    roles: list[str] = []
    try:
        text = path.read_text(encoding="utf-8")
    except Exception:
        return Entry(name, desc, path)
    if not text.startswith("---"):
        return Entry(name, desc, path)
    end = text.find("\n---", 3)
    if end < 0:
        return Entry(name, desc, path)
    in_roles = False
    for line in text[3:end].splitlines():
        # Блочный список YAML под `roles:` — строки `  - work`. Читается
        # только пока идут элементы списка; первый же другой ключ его закрывает.
        if in_roles:
            item = line.strip()
            if item.startswith("- "):
                roles.extend(_role_names(item[2:]))
                continue
            in_roles = False
        key, _, value = line.partition(":")
        key, value = key.strip(), value.strip().strip('"').strip("'")
        if key == "roles":
            roles.extend(_role_names(value))
            in_roles = not value
        elif key == "name" and value:
            name = value
        elif key == "description" and value:
            desc = value
        elif key == "drop" and value.lower() in ("true", "yes", "да", "1"):
            dropped = True
        elif key == "kind" and value:
            kind = value
        elif key == "track" and value:
            track = value
    return Entry(name, desc, path, dropped=dropped, kind=kind, track=track,
                 roles=tuple(roles))


def _role_names(value: str) -> list[str]:
    """Имена ролей из значения поля: `[work, verify]`, `work, verify`, `work`.

    Скобки инлайн-списка YAML и кавычки снимаются; регистр не важен. Мигратор
    пишет `roles: [work]` — это первая из форм, остальные две пишет человек.
    """
    value = value.strip().strip("[]")
    return [r.strip().strip('"').strip("'").lower()
            for r in value.split(",") if r.strip().strip('"').strip("'")]


def applies_to_role(entry: Entry, role: str | None) -> bool:
    """Адресована ли запись роли `role`.

    Запись без `roles` адресована всем — это правила, не зависящие от того,
    кто в сессии: зоны ответственности, передача работы, расширение памяти.
    Запись с названными ролями видна только им: правила про ветки и MR
    дежурному по инциденту не нужны, а место в потолке чтения они занимают
    ровно такое же, как нужные.

    `role` пуст — фильтра нет (сборка без роли показывает всё), как и у
    дисциплин: молча спрятать страницу от того, кто роль не назвал, хуже, чем
    показать лишнюю.
    """
    if not role or not entry.roles:
        return True
    return role.strip().lower() in entry.roles


def applies_to_tracks(entry: Entry, tracks: set[str] | None) -> bool:
    """Годится ли запись инсталляции, идущей по дисциплинам `tracks`.

    Запись без `track` и запись с `track: общее` годятся всегда — это правила,
    не зависящие от того, пишет команда код или нет. Запись с названной
    дисциплиной видна только той инсталляции, которая эту дисциплину заявила.

    `tracks` пуст или не задан — фильтра нет вовсе (прежнее поведение): пока
    владелец не сказал, чем занимается команда, показывать ей всё честнее, чем
    угадывать и молча прятать.
    """
    if not tracks:
        return True
    track = entry.track.strip().lower()
    return not track or track == "общее" or track in tracks


def layer_entries(root: Path | None, keep_dropped: bool = False,
                  tracks: set[str] | None = None,
                  role: str | None = None) -> list[Entry]:
    """Записи слоя, по алфавиту имён файлов. Нет каталога → пусто, не ошибка:
    слой может быть не заведён (у инсталляции нет слоя о человеке), и это
    штатное состояние, а не повод не запускать сессию.

    `drop: true` уважается ЗДЕСЬ, а не только в методологии. До 14.09.2026 поле
    читалось во всех слоях, а действовало в одном: запись, помеченная как
    выключенная, продолжала стоять в индексе проектного слоя и слоя о человеке.
    Пометка, которая работает в одном месте из трёх, хуже отсутствующей —
    человек считает запись убранной, а сессия её читает.

    `keep_dropped` нужен ровно одному вызывающему — сборке методологии: там
    файл клиента с `drop: true` не «выключен», а является инструкцией убрать
    одноимённый базовый.

    `role` — чью сессию собираем: запись с полем `roles`, где этой роли нет,
    в слой не попадает (см. applies_to_role).
    """
    if not root:
        return []
    try:
        files = sorted(Path(root).glob("*.md"))
    except OSError as e:
        log.warning("память: не смог прочитать слой %s (%r)", root, e)
        return []
    out = [entry_of(f) for f in files if f.name not in NOT_ENTRIES]
    if not keep_dropped:
        out = [e for e in out if not e.dropped]
    return [e for e in out
            if applies_to_tracks(e, tracks) and applies_to_role(e, role)]


def methodology_entries(base: Path | None = None,
                        override: Path | None = None,
                        tracks: set[str] | None = None,
                        role: str | None = None) -> list[Entry]:
    """Методология после переопределения: файл клиента вытесняет базовый ЦЕЛИКОМ.

    Совпадение — по имени файла, а не по `name` во frontmatter: имя файла
    видно, не читая файл, и переопределяющий его не сочинит случайно. Файл
    клиента без базового соответствия — просто добавление; файл с `drop: true`
    убирает базовый пункт и сам в индекс не попадает.

    `role` — для чьей сессии: страница, адресованная другим ролям (`roles:`),
    в индекс не идёт. Единственное, что переопределение НЕ вытесняет целиком, —
    адрес: файл клиента без `roles` наследует адрес базовой страницы. Иначе
    переопределение, написанное до появления адресации, молча вернуло бы
    правила про ветки дежурному — ровно то, от чего адресация заведена. Свой
    адрес клиент пишет явно, и тогда он главнее базового.
    """
    base_entries = {e.path.name: e
                    for e in layer_entries(base or METHODOLOGY_BASE, tracks=tracks)}
    result = dict(base_entries)
    # Переопределения читаются ВМЕСТЕ с выключенными и БЕЗ фильтра дисциплин:
    # `drop: true` здесь — инструкция убрать базовую страницу, а не признак
    # выключенной записи, и она обязана сработать независимо от того, какую
    # дисциплину заявила инсталляция.
    for own in layer_entries(override, keep_dropped=True):
        if own.dropped:
            result.pop(own.path.name, None)
            continue
        if not applies_to_tracks(own, tracks):
            continue
        inherited = base_entries.get(own.path.name)
        roles = own.roles or (inherited.roles if inherited else ())
        result[own.path.name] = Entry(own.name, own.description, own.path,
                                      overridden=inherited is not None,
                                      kind=own.kind, track=own.track, roles=roles)
    return [result[k] for k in sorted(result) if applies_to_role(result[k], role)]


def _take(entries: list[Entry], limit: int) -> tuple[list[str], list[Entry]]:
    """Строки, влезающие в limit байт, и записи, которые не влезли."""
    used, lines = 0, []
    for i, e in enumerate(entries):
        line = e.line()
        cost = len(line.encode("utf-8")) + 1
        if used + cost > limit:
            return lines, entries[i:]
        used += cost
        lines.append(line)
    return lines, []


def _fit(entries: list[Entry], limit: int) -> tuple[list[str], int, int, int]:
    """Строки и остаток за бортом: (строки, обычных, ограничений, полоса в байтах).

    Ограничения идут ПЕРВЫМИ и по своей полосе (`CONSTRAINT_BAND`), остальное
    делит остаток по алфавиту. До 14.09.2026 порядок был чисто алфавитным, и
    правило выживало или не выживало по первой букве имени файла: определение
    готовности на client-b уцелело потому, что «d» третья из шести, а не потому,
    что без него роль проверки не работает.

    Полоса не отменяет потолок, а забирает своё раньше: ограничений мало, они
    короткие, и ровно они бесполезны в урезанном виде — «не делай X, кроме» без
    продолжения хуже, чем ничего.
    """
    limits = [e for e in entries if e.is_constraint]
    rest = [e for e in entries if not e.is_constraint]
    # Полоса не больше самого раздела: раздел уже урезан тем, что съели слои
    # выше, и выдать ограничениям больше, чем есть у раздела, значило бы
    # пробить общий потолок ради полосы.
    band = min(CONSTRAINT_BAND, max(limit, 0))
    head, over_limits = _take(limits, band)
    used = sum(len(l.encode("utf-8")) + 1 for l in head)
    tail, over_rest = _take(rest, max(0, limit - used))
    return head + tail, len(over_rest), len(over_limits), band


def _section(title: str, entries: list[Entry], where: str | None,
             limit: int) -> tuple[str, int]:
    """Раздел блока: заголовок + урезанный по limit список. (текст, съедено байт).

    `where` — где лежит слой, словами: у методологии это два каталога (база и
    переопределения), и обрезанный хвост мог остаться в любом из них. None
    значит «слой не заведён вовсе», а не «пуст».

    Пустой слой печатается словами, а не пропускается: «слоя нет» — тоже
    знание, иначе сессия ищет то, чего не завели.
    """
    if not entries:
        absent = ("(слоя у этой инсталляции нет — владелец его не заводил)"
                  if where is None else
                  f"(слой пуст — записей в нём ещё нет, {where})")
        return f"{title}\n{absent}\n", 0
    lines, left, left_limits, band = _fit(entries, limit)
    used = sum(len(l.encode("utf-8")) + 1 for l in lines)
    if left:
        # Хвостовая строка в бюджет не входит и потому не вытесняет запись:
        # она фиксированной длины, а потолок заведён против растущего. Молча
        # обрезать слой нельзя — сессия не узнает, что он вообще есть.
        lines.append(f"- … ещё {left} записей не поместились в потолок индекса "
                     f"— {where}, посмотри сам, если понадобится")
    if left_limits:
        # Отдельной строкой и другими словами: обрезанное ограничение — не
        # та же новость, что обрезанная справка. Полоса рассчитана на то, что
        # ограничений единицы; переполнилась она — раскладка слоя неверна, и
        # сессия должна это видеть, а не догадываться.
        # Полоса называется ФАКТИЧЕСКАЯ, а не константа: раздел мог достаться
        # урезанным, и тогда полоса меньше `CONSTRAINT_BAND` — а то и ноль.
        # Написать «не влезло в 3000 Б», когда места было 0, значит послать
        # читателя искать несуществующую причину.
        lines.append(f"- ⚠️ ещё {left_limits} ОГРАНИЧЕНИЙ не поместились даже в "
                     f"свою полосу ({band} Б из {CONSTRAINT_BAND} возможных) — "
                     f"{where}. Либо раздел урезан слоями выше, либо видом "
                     f"«{CONSTRAINT_KIND}» помечено лишнее; прочитай каталог сам")
    body = "\n".join(lines)
    return f"{title}\n{body}\n", used


def _index_size(path: Path | None) -> int:
    """Размер индекса проектного слоя в байтах. Нет файла → 0."""
    try:
        return path.stat().st_size if path else 0
    except OSError:
        return 0


def layers_block(role_index: Path | None = None,
                 methodology_base: Path | None = None,
                 methodology_override: Path | None = None,
                 person_root: Path | None = None,
                 person_owner: str = "",
                 budget: int = DEFAULT_INDEX_MAX,
                 tracks: set[str] | None = None,
                 role: str = "") -> str:
    """Блок про два слоя на чтение — то, что дописывается к контракту памяти.

    Пусто не возвращает никогда: даже когда оба слоя пусты, сессия обязана
    знать, что писать ей можно только в проектный. Без этого методология
    расползается копиями по проектной памяти каждой инсталляции, и обновление
    продукта перестаёт что-либо значить.

    `role` — чья сессия (`work`, `verify`, `intake`, `incident`): методология и
    слой о человеке отдают ей только адресованное (`roles:` в frontmatter) и
    всё, что адреса не имеет. До 15.09.2026 роль влияла только на путь к
    проектному индексу, и дежурный по инциденту получал правила про ветки и
    MR — половину того, за что роль платит потолком чтения.
    """
    base = methodology_base or METHODOLOGY_BASE
    method_where = f"каталог {base}" + (
        f", переопределения — {methodology_override}" if methodology_override else "")
    role_bytes = _index_size(role_index)
    # Методология получает свою броню ПЕРВОЙ, остальное делит с проектным
    # индексом. Обратный порядок оставлял продуктовый слой без места ровно
    # тогда, когда он нужнее всего (см. METHODOLOGY_FLOOR).
    left = max(METHODOLOGY_FLOOR, budget - role_bytes)

    parts = [_HEAD]

    if budget - role_bytes <= 0:
        # Проектный индекс съел потолок. Методологию печатаем всё равно — в
        # пределах брони, — а про индекс говорим прямо.
        # Формулировка ровно по факту. Прежняя обещала «слой о человеке не
        # показан» и «списки урезаны» — и то и другое неправда, когда записей
        # мало и они помещаются в броню. Проза, расходящаяся с тем, что сессия
        # видит ниже по тексту, учит её не верить прозе.
        parts.append(
            f"⚠️ Индекс твоего проектного слоя занимает {role_bytes} байт при "
            f"потолке {budget} на все три слоя. Ниже — только то, что влезло в "
            f"броню методологии ({METHODOLOGY_FLOOR} Б); не поместившееся "
            f"названо строкой «ещё N записей». **Сожми индекс**: объедини "
            f"близкие записи, выброси то, что перестало быть правдой. "
            f"Проектный слой — единственный, который тебе можно править.\n")

    method = methodology_entries(base, methodology_override, tracks=tracks,
                                 role=role)
    person = layer_entries(person_root, tracks=tracks, role=role)
    method_title = _METHOD_TITLE.format(
        addressed=_ADDRESSED.format(role=role) if role else "")
    text, used = _section(method_title, method, method_where, left)
    parts.append(text)
    # Имя владельца в заголовке — чтобы сессия видела, О КОМ этот слой: она
    # и так знает, кто принимает работу, и связать одно с другим должна сама.
    person_title = _PERSON_TITLE.format(
        owner=f" ({person_owner})" if person_owner else "")
    text, _ = _section(person_title, person,
                       f"каталог {person_root}" if person_root else None,
                       max(0, left - used))
    parts.append(text)
    if role_bytes > budget // 2:
        parts.append(
            f"Твой проектный индекс — {role_bytes} байт из {budget} на все три "
            f"слоя. Дальше он вытесняет методологию: прежде чем дописывать, "
            f"сожми его — объедини близкие записи, выброси устаревшее.\n")
    return "\n".join(parts)


_HEAD = """\
### Ещё два слоя, кроме твоего

Твоя память роли — слой **проекта**: он принадлежит клиенту, нарабатывается
сессиями, и пишешь ты только в него. Кроме него тебе доступны на ЧТЕНИЕ два
слоя с другими владельцами. Их файлы сюда не грузятся — ниже индекс, файл
читай с диска по абсолютному пути, когда запись оказалась нужна.

Правило владения, которое дороже остальных: **чужой слой не переписывают
через свой.** Не согласен с методологией — скажи об этом в задаче, а не
записывай опровержение в проектную память: там оно станет местным форком
правила, и обновление продукта перестанет что-либо значить.
"""

_METHOD_TITLE = """\
**Методология — владелец продукт.** Как здесь принято работать. Приезжает с
релизом.{addressed} Клиент её не правит, а переопределяет — кладёт поверх свой
файл с тем же именем; помеченную «переопределено клиентом» запись ты читаешь
в его версии."""

# Вставка в заголовок, когда блок собран для конкретной роли. Сессия обязана
# знать, что список неполный по замыслу: иначе страницу, которую называет
# контракт другой роли, она пойдёт искать как пропавшую.
_ADDRESSED = (" Ниже — только страницы, адресованные твоей роли ({role}); "
              "остальные лежат в том же каталоге.")

_PERSON_TITLE = """\
**О человеке{owner} — владелец он сам.** Привычки того, кто ставит и принимает
работу: в каком виде он ждёт отчёт, что для него «доказано», чего не любит.
Правит их он, и переносит между своими проектами."""
