"""Личности фабрики в трекере: кто подписывается под комментарием.

До этого модуля вся фабрика ходила в трекер ОДНИМ ключом — личным ключом
владельца. Со стороны задачи это выглядело так, будто всё в ней сделал
человек: и разбор постановки, и работа, и ревью. Мультиагентность была видна
только по тексту комментариев, то есть на слово.

Личность — не то же самое, что `kind` очереди. Соответствие задаёт
`PERSONA_BY_KIND`, и оно не взаимно однозначное:

* `work` → `engineer` — обычная рабочая сессия;
* `incident` → `duty` — дежурный;
* `intake` → `intake` — приёмщик постановок. Заводит задачу и пишет разбор;
* `verify` → `qa` — проверка поведения у пользователя. Своя личность, и это
  не косметика. Ревью отвечает на вопрос «правильно ли написан код», QA — на
  вопрос «получает ли человек ожидаемое»; это разные утверждения с разными
  доказательствами. Пока оба говорили голосом Reviewer, на доске нельзя было
  отличить «я прочитал дифф» от «я постучался в дверь и посмотрел ответ», а
  доверие к этим двум видам вердиктов калибруется ПОРОЗНЬ;
* `reviewer` — ЕЩЁ и ревью-субсессия внутри работы инженера. Она не `kind`
  вовсе: сессия одна, а комментария два — от инженера и от ревьюера.

Ключ каждой личности приходит окружением инсталляции:
`LINEAR_API_KEY_ENGINEER`, `LINEAR_API_KEY_DUTY`, `LINEAR_API_KEY_INTAKE`,
`LINEAR_API_KEY_REVIEWER`. Ключа нет — пишем прежним `LINEAR_API_KEY`, то
есть ведём себя ровно как до этого модуля. Это важнее красоты: инсталляция,
которая ещё не завела приложений в трекере, не должна перестать писать
комментарии вовсе.

Что личность МОЖЕТ, решает трекер, а не этот модуль. У приложения Linear с
`actor=app` скоупы узкие (`comments:create`, `issues:create`), и правка
задачи — статус, исполнитель — в них не входит. Поэтому личность используется
для АВТОРСТВА (комментарий, создание задачи), а назначение и смена статуса
остаются на ключе инсталляции.
"""
from __future__ import annotations

# Личность по виду задачи. Незнакомый вид — как и везде в раннере — работа.
PERSONA_BY_KIND = {
    "work": "engineer",
    "incident": "duty",
    "intake": "intake",
    "verify": "qa",
}

DEFAULT_PERSONA = "engineer"

# Ревью-субсессия. Отдельной константой, потому что это единственная личность
# без своего `kind`: её зовут изнутри рабочей сессии.
REVIEWER = "reviewer"

PERSONAS = ("engineer", "duty", "intake", "reviewer", "qa")

# Чем платим за развод ролей: инсталляция, где приложения QA ещё нет, начала бы
# писать проверки общим ключом — то есть от имени человека, и вердикт выглядел
# бы как его собственный. Поэтому запасной ход у QA не общий ключ, а Reviewer:
# прежний голос честнее безымянного.
FALLBACK_PERSONA = {"qa": "reviewer"}

# Переменная окружения под ключ личности. Приставка та же, что у общего ключа,
# — чтобы в заготовке окружения они лежали рядом и читались как одно хозяйство.
KEY_PREFIX = "LINEAR_API_KEY_"


def persona_of(kind: str) -> str:
    """Личность по виду задачи из очереди."""
    return PERSONA_BY_KIND.get((kind or "").strip(), DEFAULT_PERSONA)


def key_var(persona: str) -> str:
    """Имя переменной окружения с ключом этой личности."""
    return KEY_PREFIX + (persona or "").strip().upper()


def keys_from_store(path=None) -> dict[str, str]:
    """Ключи личностей из хранилища токенов, если оно есть.

    Токен Linear живёт ровно сутки, и обновлять его должен фоновый прогон
    (`core/linear_tokens.py`), а не человек браузером. Раннер читает ключ при
    старте, поэтому обновление в переменных окружения до него не доезжает —
    хранилище доезжает, файл перечитывается на каждый вызов.

    Хранилища нет или оно битое — молча пусто: окружение остаётся рабочим
    путём, и инсталляция без обновления токенов работает как раньше.
    """
    import json as _json
    import os as _os
    from pathlib import Path as _Path
    p = _Path(path or _os.environ.get(
        "AGENT_LINEAR_TOKENS",
        str(_Path.home() / ".config" / "linear-agents" / "tokens.json")))
    try:
        data = _json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    out = {}
    for persona in PERSONAS:
        rec = data.get(persona) or data.get(persona.upper()) or {}
        value = (rec.get("access_token") or "").strip() if isinstance(rec, dict) else ""
        if value:
            out[persona] = value
    return out


def keys_from_env(env) -> dict[str, str]:
    """Ключи личностей из окружения. Пустые значения не кладём вовсе.

    Различать «переменной нет» и «переменная пустая» здесь не нужно: и то, и
    другое значит «личность не настроена, пиши общим ключом». А вот класть
    пустую строку в карту нельзя — тогда `keys.get(persona) or common` ещё
    работает, а `persona in keys` уже врёт.
    """
    out = {}
    for persona in PERSONAS:
        value = (env.get(key_var(persona)) or "").strip()
        if value:
            out[persona] = value
    # Хранилище СТАРШЕ окружения: в окружении ключ заморожен при старте
    # раннера, а в хранилище лежит тот, что обновил фоновый прогон. Порядок
    # обратный означал бы, что раннер сутками ходит мёртвым ключом, имея
    # рядом живой.
    out.update(keys_from_store())
    for persona, instead in FALLBACK_PERSONA.items():
        if persona not in out and instead in out:
            out[persona] = out[instead]
    return out

