"""Шлюз тяжёлой задачи: стратегия и проверки ДО правки кода (DEV-56).

На простой работе фабрика закрывает по три-шесть задач подряд, и шлюз ей
не нужен. Ломается она на тяжёлой: локально разумные шаги складываются в
неверную тактику — правок делается много, хотя сначала стоило воспроизвести
ошибку и усилить проверки. Один такой заход породил ещё пять-шесть задач,
часть исправлений пришлось исправлять повторно, а исходные риски не были
названы вовсе. Это промах не в коде, а в выборе стратегии до кода — и
код-ревью его не ловит: оно смотрит на уже написанное.

Поэтому у рабочей сессии появился шлюз, и он оставляет след файлом —
`plan.md` в рабочем каталоге, рядом с `handoff.md`. Файл, а не рассказ в
логе: раннер читает его тем же механизмом, что и сдачу (`handoff_misses` →
возврат сессии), и «шлюз прошли» перестаёт быть словом сессии о себе.

Раздел «Тяжесть» обязателен ВСЕГДА, остальные — только у тяжёлой:

    ## Тяжесть
    лёгкая: ни один признак не сработал          ← и это весь файл

    ## Тяжесть
    тяжёлая: конкурентность, нет-теста
    ## Факты и воспроизведение
    ...восемь разделов шлюза...
    ## Последствия
    DEV-57 — независимая находка

Так простая задача платит одну строку, а тяжёлая — то самое короткое
решение, которого не хватало. Признаки тяжести (`TRIGGERS`) и разделы
решения (`SECTIONS`) лежат здесь данными, а не прозой контракта: их читают
двое — текст промпта и линт файла, — и разъехавшись, они дали бы сессии
требование, которого она не видела.

Здесь только файл: чистые функции без трекера и без окружения, чтобы гонять
их и по записанным каталогам.
"""
from __future__ import annotations

from pathlib import Path

from handoff import key_of, sections_of

PLAN_FILE = "plan.md"

# Раздел с вердиктом — единственный обязательный для любой работы.
VERDICT_SECTION = "Тяжесть"
HEAVY = "тяжёлая"
LIGHT = "лёгкая"

# Признаки тяжести из постановки DEV-56. Ключ — короткое слово, которым
# сессия называет сработавший признак в вердикте; пояснение идёт в контракт.
# Признак называется ИМЕНЕМ, а не прозой, чтобы «тяжёлая, потому что сложно»
# нельзя было выдать за разбор: по именам видно, что именно сработало, и их
# же можно посчитать по нескольким реальным случаям.
TRIGGERS: tuple[tuple[str, str], ...] = (
    ("конкурентность", "взаимные блокировки, конкурентность и порядок событий"),
    ("прод", "отказоустойчивость, восстановление после сбоев и промышленная среда"),
    ("данные", "исторические данные, миграции или изменение схемы хранения"),
    ("широкий-охват", "несколько служб или широкий участок системы"),
    ("причина-неясна", "неясная первопричина"),
    ("нет-теста", "изменение, для которого нет воспроизводящего теста"),
    ("цена-отката", "высокая цена отката или потеря данных"),
)

# Восемь пунктов решения — ровно те, что требует постановка. Заголовок и
# подсказка: подсказку читает контракт, заголовок проверяет линт.
SECTIONS: tuple[tuple[str, str], ...] = (
    ("Факты и воспроизведение",
     "что наблюдается и какой командой это воспроизводится"),
    ("Первопричина и уверенность",
     "предполагаемая причина и насколько ты в ней уверен (высокая / средняя / "
     "догадка)"),
    ("Что проверяемо без правки кода",
     "что можно узнать, не трогая промышленный код: журнал, стенд, тест на "
     "текущем коде"),
    ("Варианты",
     "варианты действий, и среди них обязательно «не менять код: сначала "
     "тесты или наблюдение»"),
    ("Минимальный объём",
     "самое малое изменение, которое закрывает причину; всё остальное — "
     "отдельная задача"),
    ("Риски и откат",
     "чем это опасно, какие службы задеты и как откатить"),
    ("План проверок",
     "чем проверяешь ДО изменения и чем ПОСЛЕ — место, команда, ожидаемое "
     "значение"),
    ("Условия остановки",
     "какое новое свидетельство отменяет выбранную тактику и возвращает тебя "
     "к шлюзу"),
)

# Раздел, который заполняется уже ПО ХОДУ работы: что эта задача за собой
# потянула. Пишется в план, а не в сдачу, потому что читается вместе с
# выбранной тактикой: последствия — её цена.
CONSEQUENCES_SECTION = "Последствия"

# Причины появления дочерней задачи. Первые две существовали до правки и
# найдены ею, третью правка внесла сама, четвёртая — старая регрессия.
# Разделение не бухгалтерия: «нашли пять проблем» и «внесли пять проблем» —
# противоположные оценки одной и той же сессии.
REASON_INDEPENDENT = "независимая находка"
REASON_PART = "часть решения"
REASON_INTRODUCED = "внесено этой правкой"
REASON_REGRESSION = "прежняя регрессия"
REASONS: tuple[str, ...] = (REASON_INDEPENDENT, REASON_PART,
                            REASON_INTRODUCED, REASON_REGRESSION)
# Последствий не было — законный ответ, и он обязан отличаться от пустого
# раздела: «ничего не потянула» это факт, а пустота — несделанная работа.
NO_CONSEQUENCES = "нет"

# Первая строка комментария с планом в задаче. По ней следующая сессия
# отличает план от остальной переписки, а человек — видит, что от него ждут
# решения. Строка стабильная и здесь же, потому что читают её двое: контракт
# сессии (`prompt.TEMPLATE`) и человек глазами.
COMMENT_MARKER = "## Стратегия на согласование"

MISS_NO_FILE = f"нет файла `{PLAN_FILE}` (шлюз тяжёлой задачи)"
MISS_EMPTY_FILE = f"`{PLAN_FILE}` пуст"
MISS_NO_VERDICT = (
    f"в `{PLAN_FILE}` нет раздела «{VERDICT_SECTION}» с вердиктом "
    f"«{HEAVY}: <признаки>» или «{LIGHT}: ни один признак не сработал»")
MISS_NO_TRIGGER = (
    f"в `{PLAN_FILE}` вердикт «{HEAVY}», но ни один признак не назван "
    f"именем: {', '.join(name for name, _ in TRIGGERS)}")


def _norm(text: str) -> str:
    """Текст для сравнения: без регистра и без разницы «ё»/«е».

    Разница в одной букве — не ошибка сессии, а свойство письма, и ловить на
    ней значит гонять на досдачу за «тяжелая» вместо «тяжёлая».
    """
    return text.casefold().replace("ё", "е")


def verdict_of(text: str) -> str:
    """`HEAVY`, `LIGHT` или пусто, если вердикта нет.

    Смотрим только первое слово раздела: всё остальное в строке — признаки и
    пояснение. Пусто — это «шлюз не пройден», а не «лёгкая»: молчание не
    считается ответом, иначе файл без вердикта был бы пропуском по умолчанию.
    """
    body = sections_of(text).get(key_of(VERDICT_SECTION)) or ""
    head = _norm(body.strip()).lstrip("*_-• ")
    if head.startswith(_norm(HEAVY)):
        return HEAVY
    if head.startswith(_norm(LIGHT)):
        return LIGHT
    return ""


def triggers_of(text: str) -> list[str]:
    """Признаки тяжести, названные в вердикте, — в порядке `TRIGGERS`."""
    body = _norm(sections_of(text).get(key_of(VERDICT_SECTION)) or "")
    return [name for name, _ in TRIGGERS if _norm(name) in body]


def consequences(text: str) -> dict[str, int]:
    """Сколько дочерних задач и по какой причине — из раздела «Последствия».

    Строка считается последствием, если называет одну из причин: номер задачи
    разбирать не надо, трекеров у инсталляций разные, а причина — общий
    словарь. Строка с двумя причинами считается один раз, по первой из
    `REASONS`: иначе перечисление «часть решения, а не внесено этой правкой»
    удвоило бы счёт.
    """
    body = sections_of(text).get(key_of(CONSEQUENCES_SECTION)) or ""
    counts = {reason: 0 for reason in REASONS}
    for line in body.splitlines():
        low = _norm(line)
        hit = next((r for r in REASONS if _norm(r) in low), "")
        if hit:
            counts[hit] += 1
    return counts


def counts(text: str) -> dict[str, int]:
    """Числа последствий для журнала запусков (DEV-18).

    Два вопроса, ради которых раздел и заведён: сколько задача вскрыла того,
    что было до неё, и сколько внесла сама. «Часть решения» — ни то, ни
    другое: это объём выбранной тактики, и смешать его с находками значило бы
    хвалить сессию за собственный план.
    """
    per = consequences(text)
    return {
        "найдено": per[REASON_INDEPENDENT] + per[REASON_REGRESSION],
        "внесено": per[REASON_INTRODUCED],
        "часть решения": per[REASON_PART],
        "всего": sum(per.values()),
    }


def lint_text(text: str) -> list[str]:
    """Чего не хватает в плане. Пусто — шлюз пройден.

    Лёгкая задача платит одну строку вердикта: требовать с неё восемь
    разделов значило бы обложить шлюзом ровно ту работу, которая и так идёт
    хорошо, — и следующая сессия стала бы писать «лёгкая» ради скорости.
    """
    if not text.strip():
        return [MISS_EMPTY_FILE]
    verdict = verdict_of(text)
    if not verdict:
        return [MISS_NO_VERDICT]
    if verdict == LIGHT:
        return []
    misses: list[str] = []
    if not triggers_of(text):
        misses.append(MISS_NO_TRIGGER)
    found = sections_of(text)
    for name, _ in SECTIONS + ((CONSEQUENCES_SECTION,
                                "дочерние задачи с причиной появления"),):
        body = found.get(key_of(name))
        if body is None:
            misses.append(f"в `{PLAN_FILE}` нет раздела «{name}»")
        elif not body:
            misses.append(f"в `{PLAN_FILE}` раздел «{name}» пуст")
    return misses


def lint_file(workdir: Path) -> list[str]:
    """То же по файлу в рабочем каталоге. Нет файла — один промах, а не
    десять: сессии нужно одно действие, а не список."""
    try:
        text = (Path(workdir) / PLAN_FILE).read_text(errors="replace")
    except OSError:
        return [MISS_NO_FILE]
    return lint_text(text)


def plan_of(workdir: Path) -> tuple[str, list[str]]:
    """(текст плана, промахи). Текст возвращается и при промахах — человеку
    показывают то, что сессия всё-таки написала."""
    try:
        text = (Path(workdir) / PLAN_FILE).read_text(errors="replace")
    except OSError:
        return "", [MISS_NO_FILE]
    return text.strip(), lint_text(text)


def summary(workdir: Path) -> dict:
    """Что сказал шлюз — машиночитаемо, для `stats.json` и журнала.

    Пишется у каждой рабочей сессии, в том числе у лёгкой: без строки
    «лёгкая» нельзя отличить «шлюз ответил» от «шлюза не было», а именно это
    и надо увидеть на нескольких реальных случаях, прежде чем считать
    механизм работающим.
    """
    text, misses = plan_of(workdir)
    if not text:
        return {}
    return {
        "вердикт": verdict_of(text),
        "признаки": triggers_of(text),
        "последствия": counts(text),
        "промахи": misses,
    }


def triggers_block(indent: str = "   ") -> str:
    """Признаки тяжести словами — для контракта. Имя признака стоит первым:
    им сессия и отвечает в вердикте."""
    return "\n".join(f"{indent}* `{name}` — {what};" for name, what in TRIGGERS[:-1]
                     ) + f"\n{indent}* `{TRIGGERS[-1][0]}` — {TRIGGERS[-1][1]}."


def schema_block(indent: str = "   ") -> str:
    """Разделы плана словами — одна схема на контракт и на возврат «шлюз не
    пройден», чтобы сессия видела в возврате ровно то, что читала в
    постановке."""
    lines = [f"{indent}## {VERDICT_SECTION}",
             f"{indent}`{LIGHT}: ни один признак не сработал` — и на этом файл "
             f"кончается;",
             f"{indent}`{HEAVY}: <признаки через запятую>` — дальше все разделы ниже.",
             ""]
    for name, hint in SECTIONS:
        lines.append(f"{indent}## {name}")
        lines.append(f"{indent}{hint}")
        lines.append("")
    lines.append(f"{indent}## {CONSEQUENCES_SECTION}")
    lines.append(f"{indent}по строке на дочернюю задачу: номер и причина "
                 f"появления — {', '.join(REASONS)}. Ничего не потянула — "
                 f"«{NO_CONSEQUENCES}», но раздел не пустой.")
    return "\n".join(lines)
