"""Навыки: врезки контрактов, которые дословно читает несколько ролей.

**Навык переиспользуем — этим он и отличается от роли.** Одну и ту же врезку
читает и работающий агент, и проверяющий, и приёмщик, и дежурный, поэтому она
лежит здесь, а не копией в каждом контракте.

Переиспользуемая врезка сейчас ровно одна, и это измеренный факт, а не
недоделка: дословное пересечение четырёх контрактов между собой не превышает
186 символов при объёме шаблонов 7-23 тысячи (замер повторён на DEV-13
поверх сегодняшнего файла — `core/test_roles.py` его и стережёт). Места,
похожие по смыслу — гашение симптома, определение форжа, «отметься, что
взялся» — в каждой роли написаны по-своему и короче. Вынести их в общий текст
значило бы придумать общность, которой нет, и каждый контракт от этого стал
бы длиннее.

Отсюда правило для следующего, кому покажется, что навыков должно быть
больше: **врезка переезжает сюда, когда её дословно читают минимум две
роли.** Похожая по смыслу — не повод.

Врезка контракта — не то же самое, что скил в `core/skills/`: та вклеивается
в промпт всегда и потому неотделима от контракта, а скил модель зовёт сама, и
его вклад можно измерить. Разница и почему она важна — в `CLAUDE.md`, раздел
«Роли, навыки и скилы: где что лежит».
"""

MEMORY_BLOCK = """\
## Память роли

У тебя есть постоянная память, общая для всех сессий ТВОЕЙ роли и живущая
между задачами.

**В начале** — посмотри, что в ней уже есть. Возможно, эту местность уже
разбирал кто-то из твоих предшественников: как прогнать здесь тесты, как
читать прод не ломая его, какая грабля уже стоила кому-то часа. Дешевле
прочитать, чем выяснить заново.

**В конце** — запиши то, что сократит работу следующей сессии этой же роли.
Не пересказ задачи и не отчёт: одна запись — один факт, который ты установил
проверкой и который не выводится из репозитория.

Стоит записи: неочевидный факт, подтверждённый командой (а не догадка);
грабля, на которую ты наступил, и как её обойти; рецепт, который пришлось
собирать по кускам; расхождение реальности с тем, что написано в документации.

Не стоит: то, что и так лежит в репозитории (структура кода, история git,
CLAUDE.md); детали конкретно этой задачи, которые больше нигде не всплывут;
догадки, которые ты не проверил. Мусор в общей памяти дороже отсутствия
записи — его прочитают все последующие сессии и поверят.

Если записывать нечего — не записывай. Пустой заход это нормально.
"""


def memory_block(layers: str = "") -> str:
    """Контракт памяти целиком: постоянный слой роли плюс слои с другими
    владельцами, если инсталляция их завела (`memory.layers_block`).

    Слой роли описан здесь литералом, потому что он есть всегда и ничем не
    настраивается. Остальные два приходят строкой снаружи: их состав зависит
    от инсталляции, а prompt.py про её пути ничего не знает и знать не должен.
    Пусто → прежний блок без изменений, то есть прежнее поведение.
    """
    layers = (layers or "").strip()
    return MEMORY_BLOCK + (f"\n{layers}\n" if layers else "")
