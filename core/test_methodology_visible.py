"""Указатель на методологию стоит там, где сессия его увидит.

17.09.2026: живая сессия сделала работу, не прочитав ни одной страницы
методологии, и нарушила правило «доработка идёт в ТУ ЖЕ ветку» — завела вторую
ветку и второй PR. Правила при этом лежали рядом, в `core/methodology/`.

Причина: единственное упоминание методологии стояло на строке 1295 файла в
160 тысяч знаков. Оно там было — но до него не дочитывают.

Тест держит указатель В НАЧАЛЕ файла: не «есть где-то», а «видно сразу».
"""
import pathlib
import re

ПОТОЛОК = 4000  # знаков от начала: примерно первый экран


def _claude_md() -> str:
    корень = pathlib.Path(__file__).resolve().parent.parent
    return (корень / "CLAUDE.md").read_text(encoding="utf-8")


def test_the_pointer_to_the_methodology_is_near_the_top():
    голова = _claude_md()[:ПОТОЛОК]
    assert "core/methodology/" in голова, (
        "указатель на методологию не попал в первый экран CLAUDE.md — "
        "сессия до него не дочитает, как 17.09.2026")


def test_every_page_of_the_methodology_is_named():
    корень = pathlib.Path(__file__).resolve().parent
    страницы = {p.stem for p in (корень / "methodology").glob("*.md")}
    голова = _claude_md()[:ПОТОЛОК]
    не_названы = {s for s in страницы if s not in голова}
    assert not не_названы, f"страницы есть, а в указателе их нет: {sorted(не_названы)}"


def test_the_branch_rule_is_spelled_out_not_just_linked():
    """Правило про ту же ветку — то, на котором уже обожглись. Оно названо
    словами прямо в указателе, а не спрятано за ссылкой."""
    голова = _claude_md()[:ПОТОЛОК]
    assert re.search(r"ту\s+же\s+ветку", голова, re.I), (
        "правило «доработка идёт в ту же ветку» не названо в указателе")
