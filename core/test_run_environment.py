"""Окружение прогона: набор не читает настройку живой инсталляции.

Сессия агента наследует окружение юнита раннера, и до 17.09.2026 (DEV-127) это
стоило по зависшему прогону на сессию: `agent_factory/updater.py` берёт
`CORE_CHECK_INTERVAL_SEC` на импорте, и `watch(0)` уходил в `while True` на час.
Плюс два падения от `AGENT_PEOPLE_MAP` и `AGENT_VERIFY_TIMEOUT_SEC`. Снимает
это `core/conftest.py` на импорте; здесь — два сторожа на саму защиту.

Почему сторожа два. Первый ловит поломку сегодня, но на чистой машине (в CI)
проходит вхолостую — там снимать нечего. Второй не зависит от окружения вовсе:
он сверяет список приставок в `conftest.py` с тем, что код ДЕЙСТВИТЕЛЬНО читает
из окружения, и краснеет в CI тоже, как только появится настройка с новой
приставкой. Без второго список приставок протух бы молча, а цена протухания —
ровно тот зависший прогон, ради которого всё это заведено.
"""
import os
import pathlib
import re

import conftest

# `os.environ.get("ИМЯ")`, `os.environ["ИМЯ"]`, `environ.get("ИМЯ", ...)`.
_ENV_LITERAL = re.compile(r'''environ(?:\.get)?[\(\[]\s*["']([A-Z][A-Z0-9_]*)["']''')

# Столько имён скан находил, когда его писали (17.09.2026). Проверка снизу —
# чтобы сломанный скан не проходил вхолостую: найдёт он вдруг три имени, и обе
# проверки ниже станут зелёными, ничего не проверяя.
_ИМЁН_БЫЛО = 118

# Переменные, которые читает код, но настройкой инсталляции они не являются:
# их выставляет сам питон, оболочка или CI, и снимать их нельзя.
НЕ_НАСТРОЙКА_ИНСТАЛЛЯЦИИ = frozenset({"HOME", "PATH", "TMPDIR", "PYTHONPATH", "CI"})


def _имена_переменных_из_кода() -> set[str]:
    корень = pathlib.Path(__file__).parent
    имена = set()
    for файл in корень.rglob("*.py"):
        if "__pycache__" in файл.parts:
            continue
        имена.update(_ENV_LITERAL.findall(файл.read_text(encoding="utf-8", errors="replace")))
    return имена


def test_the_scan_still_sees_the_sources():
    """Скан сломался — обе проверки ниже зелёные и пустые. Ловим это здесь."""
    найдено = _имена_переменных_из_кода()
    assert len(найдено) >= _ИМЁН_БЫЛО, (
        f"скан нашёл {len(найдено)} имён вместо {_ИМЁН_БЫЛО} — сломался он, "
        "а не код; проверки ниже без него ничего не значат")
    assert "CORE_CHECK_INTERVAL_SEC" in найдено


def test_no_installation_setting_is_left_in_the_environment():
    """Сторож на сегодня: ни одной настройки инсталляции в окружении прогона.

    На чистой машине проходит вхолостую — там и снимать нечего; работает он на
    той машине, где фабрика запущена, то есть ровно там, где ломалось.
    """
    оставшиеся = sorted(имя for имя in _имена_переменных_из_кода()
                        if имя in os.environ and имя not in НЕ_НАСТРОЙКА_ИНСТАЛЛЯЦИИ
                        and имя != "AGENT_LINEAR_TOKENS")
    assert оставшиеся == [], (
        f"настройка инсталляции доехала до прогона: {оставшиеся} — "
        "см. INSTALLATION_ENV_PREFIXES в core/conftest.py")


def test_every_setting_the_code_reads_is_covered_by_the_list():
    """Сторож на завтра, и он не зависит от окружения: список приставок в
    `conftest.py` обязан покрывать всё, что код читает из окружения.

    Появится настройка с новой приставкой — эта проверка покраснеет и в CI,
    где снимать нечего, то есть раньше, чем кто-нибудь поймает зависший прогон.
    """
    непокрытые = sorted(
        имя for имя in _имена_переменных_из_кода()
        if not имя.startswith(conftest.INSTALLATION_ENV_PREFIXES)
        and имя not in conftest.INSTALLATION_ENV_NAMES
        and имя not in НЕ_НАСТРОЙКА_ИНСТАЛЛЯЦИИ)
    assert непокрытые == [], (
        f"код читает настройки, которых нет в списке снимаемых: {непокрытые}. "
        "Настройка инсталляции — в INSTALLATION_ENV_PREFIXES или "
        "INSTALLATION_ENV_NAMES (core/conftest.py); не настройка — в "
        "НЕ_НАСТРОЙКА_ИНСТАЛЛЯЦИИ здесь")
