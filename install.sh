    "$SRC/core/agent-runner.service.template" > "$TMP_UNIT"
if grep -q '__[A-Z_]*__' "$TMP_UNIT"; then
  echo "в шаблоне остались незаполненные поля:" >&2
  grep -o '__[A-Z_]*__' "$TMP_UNIT" | sort -u >&2
  rm -f "$TMP_UNIT"; exit 1
fi
if [ "$DRY" = 1 ]; then
  echo "  [dry] юнит, который был бы установлен:"
  sed 's/^/    /' "$TMP_UNIT"
