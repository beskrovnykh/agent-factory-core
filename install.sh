#!/usr/bin/env bash
# Установка agent-factory на хост инсталляции.
#
# Зачем отдельный установщик: до 09.09.2026 фабрика раскатывалась ТОЛЬКО
# через CI первого клиента — сабмодулем в его infrastructure, его джобой,
# его ключами. Поставить её кому-то ещё было нельзя не потому, что долго, а
# потому что неоткуда (DEV-10).
#
# Что ставит: ядро (core/*.py) и systemd-юнит, собранный из шаблона под эту
# инсталляцию. Чего НЕ трогает: файл окружения с секретами — он заводится
# один раз человеком и переживает обновления.
#
# Идемпотентен: гонять после каждого обновления ядра.
#
#   ./install.sh --config installation.conf
#   ./install.sh --config installation.conf --dry-run
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG=""
DRY=0
# Выкат ЗАКАНЧИВАЕТСЯ рестартом, а не раскладкой файлов. Раннер читает
# контракт (prompt.py) один раз при старте — положенная, но не подхваченная
# правка не доезжает до сессий, и признака этого нет: 13.09.2026 выкат в
# 23:37:38 положил файлы и юниты не тронул, а следующая сессия пошла по
# старому контракту, и понять это можно было только по её поведению.
# --no-restart оставлен для того, кто перезапускает сам (кнопка обновления:
# она исполняется ВНУТРИ процесса приёма и обязана делать это в своём
# порядке, иначе убивает себя до отчёта человеку).
RESTART=1
while [ $# -gt 0 ]; do
  case "$1" in
    --config) CONFIG="$2"; shift 2;;
    --dry-run) DRY=1; shift;;
    --no-restart) RESTART=0; shift;;
    *) echo "не знаю аргумента: $1" >&2; exit 2;;
  esac
done
[ -n "$CONFIG" ] || { echo "нужен --config <файл> (см. installation.conf.example)" >&2; exit 2; }
[ -f "$CONFIG" ] || { echo "нет файла конфигурации: $CONFIG" >&2; exit 2; }

# shellcheck disable=SC1090
. "$CONFIG"

: "${INSTANCE:?в конфигурации нет INSTANCE}"
: "${RUN_USER:?в конфигурации нет RUN_USER}"
: "${HOME_DIR:?в конфигурации нет HOME_DIR}"
: "${ENV_FILE:?в конфигурации нет ENV_FILE}"
: "${NODE_BIN:?в конфигурации нет NODE_BIN — каталог, где лежит claude}"
: "${MEMORY_STORE:?в конфигурации нет MEMORY_STORE — свой стор памяти инсталляции}"
WORK_ROOT="${WORK_ROOT:-$HOME_DIR/work}"
REPOS_ROOT="${REPOS_ROOT:-$HOME_DIR/repos}"
PYTHON="${PYTHON:-}"
PYTHON_VERSION="${PYTHON_VERSION:-3.12}"
MEMORY_MAX="${MEMORY_MAX:-4G}"
CPU_QUOTA="${CPU_QUOTA:-150%}"
# Сколько systemd ждёт СЛИВА раннера при stop/restart. Обязано быть больше
# бюджета самой длинной сессии: раннер по SIGTERM перестаёт брать новое и
# ждёт уже запущенные, а systemd по истечении этого срока бьёт SIGKILL'ом по
# всей cgroup — вместе с сессией пропадает и запись о её цене и ходах.
# Умолчание: бюджет сессии + 10 минут на дозапись вердикта и возврат ветки.
# Бюджет берём из файла окружения инсталляции, а не из своего умолчания:
# именно его читает раннер, и разойтись этим двум нельзя — разойдутся молча.
# Самая длинная сессия — максимум из рабочей и проверочной (у client-b
# проверка поднята до 3600 и она же дольше всех).
env_num() {
  v="$(grep -E "^$1=" "$ENV_FILE" 2>/dev/null | tail -1 | cut -d= -f2- | tr -dc '0-9' || true)"
  [ -n "$v" ] && echo "$v" || echo "$2"
}
SESSION_TIMEOUT_SEC="${SESSION_TIMEOUT_SEC:-$(env_num AGENT_SESSION_TIMEOUT_SEC 3600)}"
VERIFY_TIMEOUT_SEC="$(env_num AGENT_VERIFY_TIMEOUT_SEC 1800)"
if [ "$VERIFY_TIMEOUT_SEC" -gt "$SESSION_TIMEOUT_SEC" ]; then
  SESSION_TIMEOUT_SEC="$VERIFY_TIMEOUT_SEC"
fi
STOP_TIMEOUT="${STOP_TIMEOUT:-$(( SESSION_TIMEOUT_SEC + 600 ))}"
if [ "$STOP_TIMEOUT" -le "$SESSION_TIMEOUT_SEC" ]; then
  echo "STOP_TIMEOUT=$STOP_TIMEOUT не больше бюджета сессии $SESSION_TIMEOUT_SEC:" >&2
  echo "рестарт будет убивать сессии SIGKILL'ом вместе с записью о них" >&2
  exit 2
fi
UNIT_NAME="${UNIT_NAME:-agent-runner}"
INTAKE_UNIT_NAME="${INTAKE_UNIT_NAME:-agent-intake}"

say() { printf '  %s\n' "$*"; }

# Что именно ставим. В архиве релиза VERSION лежит рядом; при установке из
# клона его тоже видно, но версия там — та, что на ветке, а не выпущенная.
VERSION="$(cat "$SRC/VERSION" 2>/dev/null || echo "неизвестна")"
COMMIT=""
if [ -d "$SRC/.git" ]; then
  COMMIT="$(git -C "$SRC" rev-parse HEAD 2>/dev/null || echo '')"
  VERSION="$VERSION+$(git -C "$SRC" rev-parse --short HEAD 2>/dev/null || echo '?')"
fi
run() { if [ "$DRY" = 1 ]; then printf '  [dry] %s\n' "$*"; else eval "$@"; fi; }

# ── интерпретатор ────────────────────────────────────────────────────────
#
# Стек несёт свой питон, а не пользуется системным. Причин две, и обе про
# чужой сервер:
#
#   • Питон — зависимость АГЕНТСКОГО СТЕКА, а не проекта клиента. Продукт
#     клиента может быть хоть на Kotlin; требовать от его админа поставить
#     нам интерпретатор (а на Ubuntu 22.04 — ещё и сторонний PPA, там 3.12
#     нет в штатных репозиториях) значит упереться в разговор на ровном месте.
#   • Системный питон трогать нельзя: на нём живут чужие сервисы. На
#     bluefreedom это Doc и capitain, собранные под 3.10.
#
# uv ставит standalone-сборку в домашний каталог за секунду, без root и без
# PPA, и делает venv — тогда `pip install` не лезет в систему вовсе.
#
# PYTHON в конфигурации остаётся: если у инсталляции уже есть подходящий
# интерпретатор, добывать второй незачем.
echo "== интерпретатор"
VENV="$HOME_DIR/.venv"
if [ -n "$PYTHON" ]; then
  [ -x "$PYTHON" ] || { echo "в конфигурации PYTHON=$PYTHON, но его нет" >&2; exit 1; }
  say "задан в конфигурации: $($PYTHON -V 2>&1)"
else
  UV="$(command -v uv || echo "$HOME/.local/bin/uv")"
  if [ ! -x "$UV" ]; then
    say "uv не найден, ставлю в домашний каталог"
    run "curl -LsSf https://astral.sh/uv/install.sh | sh >/dev/null"
    UV="$HOME/.local/bin/uv"
  fi
  if [ "$DRY" = 1 ]; then
    say "[dry] uv python install $PYTHON_VERSION; uv venv --python $PYTHON_VERSION $VENV"
    PYTHON="$VENV/bin/python"
  else
    "$UV" python install "$PYTHON_VERSION" >/dev/null 2>&1 || true
    if [ -x "$VENV/bin/python" ]; then
      # Установщик зовут не только на пустом месте: обновление — это тот же
      # запуск. `uv venv` на существующем окружении падает, и обновление
      # умирало на первом же шаге, не дойдя ни до ядра, ни до юнитов.
      say "окружение уже есть, оставляю"
    else
      "$UV" venv --python "$PYTHON_VERSION" "$VENV" >/dev/null
    fi
    PYTHON="$VENV/bin/python"
    say "свой: $($PYTHON -V 2>&1) ($VENV)"
  fi
fi

echo "== зависимости"
if [ "$DRY" = 1 ]; then
  say "[dry] pip install -r requirements.txt"
elif [ -n "${UV:-}" ] && [ -x "${UV:-}" ]; then
  "$UV" pip install --python "$PYTHON" -q -r "$SRC/requirements.txt"
  say "поставлены в $VENV"
else
  "$PYTHON" -m pip install -q -r "$SRC/requirements.txt"
  say "поставлены"
fi

echo "== agent-factory $VERSION"

echo "== проверки перед установкой"
# Проверяем ДО того, как что-то ставить: раннер, упавший через минуту после
# установки на отсутствующем claude, выглядит как поломка продукта, а не как
# недонастроенный хост.
if [ "$DRY" != 1 ]; then
  "$PYTHON" -c 'import redis' 2>/dev/null || { echo "нет модуля redis для $PYTHON" >&2; exit 1; }
