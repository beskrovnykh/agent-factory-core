  echo "ни в комплекте ($SRC/core/skills/code-review): рабочие сессии пойдут" >&2
  echo "без ревью, и признака этого не будет" >&2
  exit 1
fi

echo "== юнит $UNIT_NAME"
TMP_UNIT="$(mktemp)"
sed -e "s|__INSTANCE__|$INSTANCE|g" \
    -e "s|__USER__|$RUN_USER|g" \
    -e "s|__HOME__|$HOME_DIR|g" \
    -e "s|__ENV_FILE__|$ENV_FILE|g" \
