rm -f "$TMP_UNIT"

echo "== юнит $INTAKE_UNIT_NAME"
TMP_INTAKE="$(mktemp)"
sed -e "s|__INSTANCE__|$INSTANCE|g" \
    -e "s|__USER__|$RUN_USER|g" \
    -e "s|__HOME__|$HOME_DIR|g" \
    -e "s|__ENV_FILE__|$ENV_FILE|g" \
    -e "s|__PYTHON__|$PYTHON|g" \
    -e "s|__VERSION__|$VERSION|g" \
    "$SRC/core/agent-intake.service.template" > "$TMP_INTAKE"
if grep -q '__[A-Z_]*__' "$TMP_INTAKE"; then
  echo "в шаблоне приёма остались незаполненные поля:" >&2
  grep -o '__[A-Z_]*__' "$TMP_INTAKE" | sort -u >&2
  rm -f "$TMP_INTAKE"; exit 1
fi
if [ "$DRY" = 1 ]; then
  echo "  [dry] юнит приёма, который был бы установлен:"
  sed 's/^/    /' "$TMP_INTAKE"
else
  sudo install -m 644 "$TMP_INTAKE" "/etc/systemd/system/${INTAKE_UNIT_NAME}.service"
  sudo systemctl daemon-reload
  say "/etc/systemd/system/${INTAKE_UNIT_NAME}.service"
fi
rm -f "$TMP_INTAKE"

echo "== окружение: чего не хватает"
# Проверяем ПОСЛЕ установки файлов, но ДО того, как человек запустит юнит:
# пустой ключ трекера обнаружится иначе только на первой задаче.
LACK=""
# `|| true` на каждом чтении не украшение: под `set -e` с `pipefail` grep,
# не нашедший ключа, роняет ВЕСЬ установщик — а не найти его тут штатно, мы
# ровно отсутствующие и ищем. 11.09.2026 из-за этого установщик молча выходил
# с кодом 1 после успешной установки: файлы раскладывались (это раньше по
# тексту), и заметили только когда исход проверила кнопка обновления.
val_of() { grep -E "^$1=" "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- || true; }
if [ -f "$ENV_FILE" ] && [ "$DRY" != 1 ]; then
  for k in LINEAR_API_KEY AGENT_KNOWN_REPOS AGENT_ENV_CANON; do
    v="$(val_of "$k" | tr -d '"'"'"'\"')"
    [ -n "$v" ] || LACK="$LACK $k"
  done
  tok="$(val_of CLAUDE_CODE_OAUTH_TOKEN)"
  if [ -z "$tok" ]; then
    # Не ошибка: сессии пойдут по OAuth хоста. Но клиенту так оставлять
    # нельзя, и молчать об этом тоже — раннер стартует, а падает на первой
    # сессии, что выглядит как поломка продукта.
    if "$NODE_BIN/claude" auth status 2>/dev/null | grep -q '"loggedIn": *true'; then
      say "токен модели не задан — пойдёт по OAuth хоста (для клиента задать свой)"
    else
      LACK="$LACK CLAUDE_CODE_OAUTH_TOKEN(и OAuth хоста тоже нет)"
    fi
  fi
fi
# Приём — не обязателен, но полуготовым его оставлять нельзя: юнит с
# Restart=always и незаданным списком допущенных уходит в вечный цикл
# перезапусков, и это выглядит как поломка продукта.
INTAKE_READY=1
if [ -f "$ENV_FILE" ] && [ "$DRY" != 1 ]; then
  for k in TELEGRAM_BOT_TOKEN INTAKE_ALLOWED_USER_IDS; do
    v="$(val_of "$k" | tr -d '"'"'"'\"')"
    [ -n "$v" ] || INTAKE_READY=0
  done
  [ "$INTAKE_READY" = 1 ] || say "приём не настроен (TELEGRAM_BOT_TOKEN / INTAKE_ALLOWED_USER_IDS) — юнит поставлен, но не запускай его, пока не заполнишь"
fi

if [ -n "$LACK" ]; then
  say "НЕ ЗАПОЛНЕНО:$LACK"
  say "дозаполнить $ENV_FILE, потом запускать"
else
  [ "$DRY" = 1 ] || say "всё обязательное на месте"
fi

# ── что выключено (DEV-118) ─────────────────────────────────────────────
#
# Проверка выше отвечает на вопрос «не сломано ли»: три обязательные
# переменные, токен модели, готовность приёма. На вопрос «ЧТО ВЫКЛЮЧЕНО» она
# не отвечает — всё, чего нет в её списке, для неё не существует. Разница
# дорогая: сломанное видно по падению, выключенное не видно вообще. Кнопки
# «Смержить» на странице очереди не было месяц, потому что не задана
# `AGENT_HOSTING_SOURCE`, — и установщик при этом честно докладывал «всё
# обязательное на месте».
#
# Поэтому список выключенных способностей печатается на каждой установке, и
# он НЕ МЕНЯЕТ кода возврата: выключено по решению — это норма, а ненулевой
# код вернул бы нас ровно к молчанию (выключали бы тихо, лишь бы установщик
# был зелёным). Тот же список доступен отдельной командой, без переустановки,
# — она печатается ниже.
echo "== способности: что выключено"
if [ "$DRY" = 1 ]; then
  say "[dry] перечислил бы выключенные способности по $ENV_FILE"
else
  "$PYTHON" "$HOME_DIR/capabilities.py" --env-file "$ENV_FILE" 2>&1 | sed 's/^/  /' || true
  say "тот же список потом:          $PYTHON $HOME_DIR/capabilities.py --env-file $ENV_FILE --all"
fi

# ── база знаний проекта (DEV-41) ────────────────────────────────────────
#
# Проверка выше смотрит, ЗАПОЛНЕНЫ ли поля. Эта — отвечают ли непусто те
# точки, куда сессия за знанием придёт: список репозиториев, канон
# окружений, `CLAUDE.md` каждого клона, каталоги памяти ролей. Разница
# видна на первой же установке: `AGENT_KNOWN_REPOS` заполнен, а половина
# клонов без `CLAUDE.md` — и сессия, посланная контрактом читать «чем
# проверять», читает пустоту.
#
# Ненулевой код аудита — результат, а не сбой установки: под `set -e` он
# оборвал бы установщик на последнем шаге, поэтому `|| true`.
echo "== база знаний проекта"
if [ "$DRY" = 1 ]; then
  say "[dry] прогнал бы knowledge.py audit по $REPOS_ROOT"
else
  "$PYTHON" "$HOME_DIR/knowledge.py" audit --repos-root "$REPOS_ROOT" --env-file "$ENV_FILE" 2>&1 | sed 's/^/  /' || true
  say "черновик списка репозиториев: $PYTHON $HOME_DIR/knowledge.py draft --repos-root $REPOS_ROOT"
  say "что спросить у команды:       $PYTHON $HOME_DIR/knowledge.py questions --repos-root $REPOS_ROOT --env-file $ENV_FILE"
fi

# Отметка установленного. Её читает слежение за версией, чтобы понять, отстала
# ли площадка: клон уходит вперёд задолго до установки, и спрашивать его
# бесполезно. Раньше отметку писала ТОЛЬКО кнопка обновления — значит установка
# руками оставляла её протухшей, и слежение считало площадку отставшей на то,
# что на ней уже стоит. 11.09.2026 это трижды кончилось предложением обновиться
# в никуда.
if [ -n "$COMMIT" ] && [ "$DRY" != 1 ]; then
  printf '%s' "$COMMIT" > "$HOME_DIR/.installed-version"
  say "отметка версии: $(printf '%s' "$COMMIT" | cut -c1-8)"
fi

# ── подхват: файлы положены, теперь их надо ПРОЧИТАТЬ ───────────────────
#
# Факт рестарта записываем в двух местах: файлом рядом с ядром (его читает
# человек и кнопка обновления) и строкой в журнале (её видно рядом с логами
# сессий, и по ней можно сказать, каким контрактом собрана конкретная
# сессия). Раньше не записывали нигде — и прошлые вердикты нельзя было
# размечать, потому что версия харнеса на момент сессии неизвестна.
restart_note() {
  if [ "$DRY" = 1 ]; then printf '  [dry] отметка: %s\n' "$*"; return 0; fi
  printf '%s %s\n' "$(date -Is)" "$*" >> "$HOME_DIR/.restart-log" 2>/dev/null || true
  logger -t agent-factory-install "$*" 2>/dev/null || true
}

busy_sessions() {
  pid="$(systemctl show -p MainPID --value "$UNIT_NAME" 2>/dev/null || echo 0)"
  [ -n "$pid" ] && [ "$pid" != "0" ] || { echo 0; return 0; }
  pgrep -P "$pid" 2>/dev/null | wc -l | tr -d ' '
}

echo "== подхват новой раскладки"
if [ "$RESTART" != 1 ]; then
  say "рестарт не мой (--no-restart) — перезапускает вызвавший"
  restart_note "выкат $VERSION ($(printf '%s' "$COMMIT" | cut -c1-8)): файлы положены, рестарт за вызвавшим (--no-restart)"
elif [ "$DRY" = 1 ]; then
  say "[dry] перезапустил бы $UNIT_NAME и $INTAKE_UNIT_NAME"
else
  for u in "$UNIT_NAME" "$INTAKE_UNIT_NAME"; do
    sudo systemctl is-active --quiet "$u" 2>/dev/null || { say "$u не запущен — нечего перезапускать"; continue; }
    if [ "$u" = "$UNIT_NAME" ] && [ "$(busy_sessions)" != "0" ]; then
      # Слив теперь безопасен (TimeoutStopSec больше бюджета сессии), но
      # стоит до часа ожидания — установщик, вставший на час, выглядит как
      # зависший. Поэтому не молчим и не ждём: говорим прямо, что контракт
      # доедет только после рестарта, и оставляем это человеку.
      say "$u ЗАНЯТ сессией — НЕ перезапускаю"
      say "  новый контракт доедет только после: sudo systemctl restart $u"
      restart_note "выкат $VERSION ($(printf '%s' "$COMMIT" | cut -c1-8)): $u занят сессией, НЕ перезапущен — сессии идут по старому контракту"
      continue
    fi
    if [ "$u" = "$INTAKE_UNIT_NAME" ]; then
      # Отложенно и ОТДЕЛЬНЫМ процессом: обновление по кнопке исполняется
      # внутри приёма, и прямой restart убил бы установщик на полуслове.
      sudo systemd-run --quiet --on-active=5 \
        --unit="agent-intake-restart-after-install" \
        /usr/bin/systemctl restart "$u" 2>/dev/null \
        || sudo systemctl restart "$u"
      say "$u перезапустится через 5 с"
    else
      sudo systemctl restart "$u"
      say "$u перезапущен"
    fi
    restart_note "выкат $VERSION ($(printf '%s' "$COMMIT" | cut -c1-8)): $u перезапущен"
  done
fi

echo "== готово"
if [ "$DRY" = 1 ]; then
  say "ничего не изменено (--dry-run)"
else
  say "запустить:   sudo systemctl enable --now $UNIT_NAME"
  say "перезапуск:  sudo systemctl restart $UNIT_NAME"
  say "логи:        sudo journalctl -u $UNIT_NAME -f"
  if [ "$INTAKE_READY" = 1 ]; then
    say "приём:       sudo systemctl enable --now $INTAKE_UNIT_NAME"
  fi
fi
